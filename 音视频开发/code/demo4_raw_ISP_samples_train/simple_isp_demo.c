/*
 * ============================================================================
 * simple_isp_demo.c — 一个用于教学演示的完整 ISP Pipeline 实现
 * ============================================================================
 *
 * 【什么是 ISP Pipeline？】
 * ISP（Image Signal Processor，图像信号处理器）是相机系统中不可或缺的一环。
 * 当你按下快门时，图像传感器（CMOS/CCD）输出的并不是我们熟悉的 JPEG/PNG 图片，
 * 而是一种叫做 "Bayer Raw" 的原始数据。ISP 的工作就是经过一系列处理步骤，
 * 将这份原始数据 "烹饪" 成我们眼睛能正常观看的彩色图像。
 *
 * 【Pipeline（流水线）设计模式】
 * 这个程序展示了工业界最常用的架构模式之一：Pipeline（流水线）。
 *
 * Pipeline 的核心思想：将一个复杂的任务拆分成多个独立的小阶段（Stage），
 * 数据像流水一样依次经过每个阶段。每个阶段只做一件事，做好后把结果交给下一个阶段。
 *
 * 优点：
 *   - 每个阶段职责单一，易于理解和调试
 *   - 可以单独调节每个阶段的参数
 *   - 可以保存中间结果，方便观察每一步的效果
 *   - 各阶段可以独立优化或替换
 *
 * 类比：就像工厂的流水线 —
 *   原料（Sensor Bayer Raw）
 *     → 工序1：黑电平校正 （去除传感器的"底噪"）
 *     → 工序2：镜头阴影校正 + 白平衡 （修正亮度和色偏）
 *     → 工序3：去马赛克 + 颜色校正 + 饱和度 + Gamma （生成彩色图）
 *     → 工序4：色彩空间转换 （RGB → YUV，适配显示/编码）
 *     → 成品（可观看的图像）
 *
 * 【本程序包含的 ISP Pipeline 阶段】
 *
 *   阶段0: 模拟 Sensor 原始数据生成（可选，用一张普通图片逆向模拟传感器输出）
 *   阶段1: 黑电平校正  (Black Level Correction)
 *   阶段2: 镜头阴影校正 (Lens Shading Correction, LSC) + 白平衡 (White Balance, WB)
 *   阶段3: 去马赛克 (Demosaicing) + 颜色校正矩阵 (CCM) + 饱和度 + Gamma 校正
 *   阶段4: 色彩空间转换 (RGB → YUV 4:2:0)
 *
 * 每个阶段的中间结果都会被保存为文件，方便你逐步观察图像的变化。
 *
 * 【运行方式】
 *   编译: gcc -o isp_demo simple_isp_demo.c -lm
 *   运行: ./isp_demo --base-rgb input.rgb --output-dir ./output --generate-previews
 *
 * 【依赖】
 *   - C99 标准库（stdio, stdlib, math, string）
 *   - ffmpeg（用于生成 PNG 预览图，非必须）
 */

/* ====================================================================
 * 头文件引入
 * ==================================================================== */
#include <errno.h>   // errno 全局变量，用于获取系统调用的错误码
#include <math.h>    // 数学函数：powf（幂运算）等
#include <stdbool.h> // C 语言中的 bool 类型（true / false）
#include <stdint.h>  // 固定宽度整数类型：uint8_t（无符号8位整数，范围 0-255）
#include <stdio.h>   // 标准输入输出：printf, fprintf, fopen, fread, fwrite 等
#include <stdlib.h>  // 标准库：malloc, free, exit, strtol, strtof, system 等
#include <string.h>  // 字符串操作：strcmp（字符串比较）等

/* ====================================================================
 * 跨平台目录创建宏
 * ====================================================================
 * Windows 使用 <direct.h> 中的 _mkdir
 * Linux/macOS 使用 <sys/stat.h> 中的 mkdir
 * 这个宏让我们写一份代码就能在两个平台上编译运行
 */
#ifdef _WIN32
#include <direct.h>
#define MKDIR(path) _mkdir(path)         // Windows: 只需要路径参数
#else
#include <sys/stat.h>
#define MKDIR(path) mkdir((path), 0755)  // Unix: 路径 + 权限（0755 = rwxr-xr-x）
#endif

/* ====================================================================
 * 配置结构体 —— ISP Pipeline 的"控制面板"
 * ====================================================================
 *
 * 结构体（struct）是 C 语言中组织相关数据的方式。
 * 这里把所有可以调节的参数都放在 Config 里，一次传入，各阶段共享。
 *
 * 每个字段的含义见下方注释。
 */
typedef struct Config {
    // ---- 输入/输出路径 ----
    const char *base_rgb_path;        // 基准 RGB 原图的文件路径（用于模拟生成 Bayer Raw）
    const char *input_bayer_path;     // 输入的 Bayer Raw 文件路径
    const char *generated_bayer_path; // 生成的 Bayer Raw 输出路径
    const char *output_dir;           // 所有输出文件的存放目录

    // ---- 图像尺寸 ----
    int width;                        // 图像宽度（像素）
    int height;                       // 图像高度（像素）

    // ---- ISP 各阶段参数 ----
    int black_level;                  // 黑电平值（传感器即使在全黑下也有一个基础电压偏移）
    float wb_r;                       // 白平衡 — 红色通道增益（>1 = 增强红色，<1 = 抑制红色）
    float wb_g;                       // 白平衡 — 绿色通道增益（通常保持接近 1.0）
    float wb_b;                       // 白平衡 — 蓝色通道增益
    float lsc_strength;               // 镜头阴影校正强度（越大，边缘提亮越多）
    float gamma;                      // Gamma 值（通常 2.2，模拟人眼和显示器的非线性响应）
    float ccm_strength;               // 颜色校正矩阵强度（0=不校正，1=完全校正，2=过度校正）
    float saturation;                 // 饱和度（1.0=原始，>1.0=更鲜艳，<1.0=偏灰）
    float artifact_strength;          // 模拟传感器伪影的强度（仅用于生成测试数据）

    // ---- 功能开关 ----
    bool generate_previews;           // 是否调用 ffmpeg 生成 PNG 预览图
    bool skip_generate;               // 是否跳过 Bayer Raw 生成步骤（已有数据则跳过）
} Config;

/* ====================================================================
 * ╔═══════════════════════════════════════════════════════════════════╗
 * ║                    第 1 部分：工具函数                              ║
 * ║                （Pipeline 的"基础设施"）                            ║
 * ╚═══════════════════════════════════════════════════════════════════╝
 * ====================================================================
 *
 * 这些是 ISP Pipeline 中反复用到的底层工具函数。
 * 好的工程实践是：把公用逻辑抽取成小函数，而不是到处复制粘贴。
 */

/*
 * clamp01 —— 把一个浮点数限制在 [0.0, 1.0] 范围内
 *
 * 为什么需要？在图像处理中，我们经常用 0.0~1.0 的浮点数表示像素值
 * （0.0 = 纯黑，1.0 = 纯白/该颜色的最大值）。
 * 但多次加减乘除后，值可能溢出这个范围，所以需要 "夹紧"。
 *
 * 参数: value - 任意浮点数
 * 返回: 限制到 [0, 1] 的值
 */
static float clamp01(float value)
{
    if (value < 0.0f)
        return 0.0f;
    if (value > 1.0f)
        return 1.0f;
    return value;
}

/*
 * clamp_u8 —— 把浮点数转换为 uint8_t（0~255 整数），并四舍五入
 *
 * 为什么需要？最终写入文件或显示到屏幕时，像素值必须是 0~255 的整数。
 * 四舍五入（+0.5 后取整）比直接截断更精确。
 *
 * 参数: value - 任意浮点数（通常是 clamp01 后的结果 * 255.0）
 * 返回: 0~255 的整数
 */
static uint8_t clamp_u8(float value)
{
    if (value < 0.0f)
        return 0;
    if (value > 255.0f)
        return 255;
    return (uint8_t)(value + 0.5f);  // +0.5 实现四舍五入
}

/*
 * clamp_non_negative —— 把浮点数限制为非负数（>= 0）
 *
 * 用于确保某些物理量（如强度、增益）不为负值。
 */
static float clamp_non_negative(float value)
{
    return value < 0.0f ? 0.0f : value;
}

/*
 * ensure_dir —— 确保目录存在，不存在则创建
 *
 * 如果目录已存在（errno == EEXIST），也视为成功。
 * 这是在写入 Pipeline 各阶段输出文件前调用的。
 *
 * 返回: 0 = 成功, -1 = 失败
 */
static int ensure_dir(const char *path)
{
    int ret = MKDIR(path);
    if (ret == 0 || errno == EEXIST)
        return 0;
    fprintf(stderr, "Failed to create directory %s\n", path);
    return -1;
}

/*
 * read_file_exact —— 精确读取一个文件的全部内容到内存
 *
 * ISP 处理中，整张图像的数据需要一次性加载到内存中进行处理。
 * 这个函数会检查实际读取的字节数是否和预期一致，防止不完整读取。
 *
 * 参数:
 *   path          - 文件路径
 *   expected_size - 期望的字节数（width * height 或 width * height * 3）
 *
 * 返回: 指向已分配内存的指针（调用者负责 free），失败返回 NULL
 */
static uint8_t *read_file_exact(const char *path, size_t expected_size)
{
    FILE *fp = fopen(path, "rb");  // "rb" = 以二进制只读方式打开
    uint8_t *buffer;
    size_t read_size;

    if (!fp) {
        fprintf(stderr, "Failed to open %s\n", path);
        return NULL;
    }

    buffer = (uint8_t *)malloc(expected_size);
    if (!buffer) {
        fclose(fp);
        fprintf(stderr, "Out of memory reading %s\n", path);
        return NULL;
    }

    read_size = fread(buffer, 1, expected_size, fp);
    fclose(fp);

    if (read_size != expected_size) {
        fprintf(stderr, "Size mismatch for %s: got %lu, expected %lu\n",
                path, (unsigned long)read_size, (unsigned long)expected_size);
        free(buffer);
        return NULL;
    }

    return buffer;
}

/*
 * write_file —— 将内存中的数据写入文件（Raw 二进制格式）
 *
 * Raw 文件没有任何头部信息，就是纯粹的像素数据流。
 * 例如一张 640x480 的灰度图 Raw = 640*480 = 307200 字节。
 *
 * 返回: 0 = 成功, -1 = 失败
 */
static int write_file(const char *path, const void *payload, size_t size)
{
    FILE *fp = fopen(path, "wb");  // "wb" = 以二进制写入方式打开
    if (!fp) {
        fprintf(stderr, "Failed to write %s\n", path);
        return -1;
    }

    if (fwrite(payload, 1, size, fp) != size) {
        fclose(fp);
        fprintf(stderr, "Short write for %s\n", path);
        return -1;
    }

    fclose(fp);
    return 0;
}

/*
 * write_pgm —— 写入 PGM（Portable Gray Map）格式的灰度图像
 *
 * PGM 是一种最简单的图像格式，带有一个可读的文件头，方便快速查看。
 * 格式：
 *   P5           ← 魔法数字，表示二进制灰度图
 *   width height ← 图像尺寸
 *   255          ← 最大灰度值
 *   [像素数据...] ← 紧随其后的是原始字节流
 *
 * 用 ImageMagick 的 display 或 ffplay 都可以直接查看 PGM 文件。
 */
static int write_pgm(const char *path, int width, int height, const uint8_t *payload, size_t size)
{
    FILE *fp = fopen(path, "wb");
    if (!fp) {
        fprintf(stderr, "Failed to write %s\n", path);
        return -1;
    }
    fprintf(fp, "P5\n%d %d\n255\n", width, height);  // 写入 PGM 文件头
    if (fwrite(payload, 1, size, fp) != size) {
        fclose(fp);
        fprintf(stderr, "Short write for %s\n", path);
        return -1;
    }
    fclose(fp);
    return 0;
}

/*
 * write_ppm —— 写入 PPM（Portable Pixel Map）格式的彩色图像
 *
 * PPM 是 PGM 的彩色版本，RGB 三通道交织排列。
 * 格式：
 *   P6           ← 魔法数字，表示二进制彩色图
 *   width height ← 图像尺寸
 *   255          ← 每个通道的最大值
 *   [RGB交织数据...] ← R,G,B,R,G,B,... 依次排列
 *
 * 每个像素占 3 个字节（R 1字节 + G 1字节 + B 1字节）。
 */
static int write_ppm(const char *path, int width, int height, const uint8_t *payload, size_t size)
{
    FILE *fp = fopen(path, "wb");
    if (!fp) {
        fprintf(stderr, "Failed to write %s\n", path);
        return -1;
    }
    fprintf(fp, "P6\n%d %d\n255\n", width, height);  // 写入 PPM 文件头
    if (fwrite(payload, 1, size, fp) != size) {
        fclose(fp);
        fprintf(stderr, "Short write for %s\n", path);
        return -1;
    }
    fclose(fp);
    return 0;
}

/*
 * generate_preview_png —— 用 ffmpeg 将 Raw 文件转换为 PNG 预览图
 *
 * 为什么需要？
 * PGM/PPM 不如 PNG 方便（浏览器、文件管理器都可以直接预览 PNG）。
 *
 * 原理：调用系统的 ffmpeg 命令行工具，读取 rawvideo 格式并编码为 PNG。
 *
 * ffmpeg 命令拆解：
 *   ffmpeg -y               ← -y: 覆盖已存在的输出文件
 *          -hide_banner     ← 不显示 ffmpeg 的版本横幅
 *          -loglevel error  ← 只显示错误信息
 *          -f rawvideo      ← 输入格式：原始视频流
 *          -pixel_format XX ← 像素格式：gray（灰度）、rgb24（RGB）、yuv420p
 *          -video_size WxH  ← 视频/图像的宽高
 *          -i INPUT         ← 输入文件
 *          -frames:v 1      ← 只输出 1 帧（因为输入是单张图片而非视频）
 *          OUTPUT           ← 输出 PNG 文件
 */
static int generate_preview_png(const char *raw_path,
                                const char *preview_path,
                                const char *pixel_format,
                                int width,
                                int height)
{
    char command[1600];  // 命令行缓冲区（1600 字节足够安全）
    int written = snprintf(
        command,
        sizeof(command),
        "ffmpeg -y -hide_banner -loglevel error -f rawvideo -pixel_format %s "
        "-video_size %dx%d -i \"%s\" -frames:v 1 \"%s\"",
        pixel_format,
        width,
        height,
        raw_path,
        preview_path);

    if (written <= 0 || written >= (int)sizeof(command)) {
        fprintf(stderr, "Preview command too long for %s\n", raw_path);
        return -1;
    }

    if (system(command) != 0) {
        fprintf(stderr, "Warning: failed to generate preview for %s\n", raw_path);
        return -1;
    }

    return 0;
}

/*
 * plane_to_u8 —— 将浮点平面数据转换为 8 位整数
 *
 * 输入:  float 数组，值应在 [0.0, 1.0] 范围内
 * 输出:  uint8_t 数组，值在 [0, 255] 范围内
 *
 * 转换过程：clamp01 → 乘 255 → clamp_u8（含四舍五入）
 */
static void plane_to_u8(const float *plane, uint8_t *out, int count)
{
    int i;
    for (i = 0; i < count; ++i)
        out[i] = clamp_u8(clamp01(plane[i]) * 255.0f);
}

/* ====================================================================
 * ╔═══════════════════════════════════════════════════════════════════╗
 * ║              第 2 部分：模拟 Sensor 原始数据生成                     ║
 * ║            （Pipeline 的"原料工厂"）                                ║
 * ╚═══════════════════════════════════════════════════════════════════╝
 * ====================================================================
 *
 * ╔═══════════════════════════════════════════════════════════════════════════╗
 * ║                   Bayer Raw 格式深度解析                                  ║
 * ║              "这个 .raw 文件里到底存的是什么？"                              ║
 * ╚═══════════════════════════════════════════════════════════════════════════╝
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 一、从物理传感器说起
 * ───────────────────────────────────────────────────────────────────────────
 *
 * 一张 640×480 的 CMOS 传感器，表面上有 640×480 = 307,200 个微小的光电二极管
 * （像素单元）。每个像素单元就是一个"光子计数器"——光子打进去，产生电子，电子被
 * 读出电路转换成数字。
 *
 * 关键问题：光电二极管只能感知光的"强度"（亮度），不能感知"颜色"（波长）。
 *           它就像一个盲人，能感受到阳光的温暖，但不知道阳光是什么颜色。
 *
 * 解决方案：在每个像素单元上覆盖一个微型彩色滤镜（Color Filter）。这样一来：
 *   - 盖了红色滤镜的像素 → 只接收红光，输出该位置的"红色强度值"
 *   - 盖了绿色滤镜的像素 → 只接收绿光，输出该位置的"绿色强度值"
 *   - 盖了蓝色滤镜的像素 → 只接收蓝光，输出该位置的"蓝色强度值"
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 二、Bayer Pattern（拜尔排列）—— 彩色滤镜的排列规则
 * ───────────────────────────────────────────────────────────────────────────
 *
 * Bryce Bayer 在 1974 年提出了最经典的滤镜排列方式。以最常见的 RGGB 为例：
 *
 *   列:  0     1     2     3     4     5   ...
 *        ↓     ↓     ↓     ↓     ↓     ↓
 *   行0 → R  ,  G  ,  R  ,  G  ,  R  ,  G  , ...   ← 偶数行：R 和 G 交替
 *   行1 → G  ,  B  ,  G  ,  B  ,  G  ,  B  , ...   ← 奇数行：G 和 B 交替
 *   行2 → R  ,  G  ,  R  ,  G  ,  R  ,  G  , ...   ← 偶数行
 *   行3 → G  ,  B  ,  G  ,  B  ,  G  ,  B  , ...   ← 奇数行
 *   ...
 *
 * 每个像素的颜色可以通过行列号判断：
 *   (y 是偶数, x 是偶数) → R  像素
 *   (y 是偶数, x 是奇数) → G  像素（通常叫 Gr，即"R 行中的 G"）
 *   (y 是奇数, x 是偶数) → G  像素（通常叫 Gb，即"B 行中的 G"）
 *   (y 是奇数, x 是奇数) → B  像素
 *
 * 注意：Gr 和 Gb 物理上都接收绿光，但因为周围像素（R vs B）不同，两者的串扰
 *       特性有微小差异。高级 ISP 算法会区分 Gr 和 Gb 来做更精确的校正。
 *
 * 为什么绿色占 50%（4 个中占 2 个）？
 *   人眼视网膜上的视锥细胞：约 64% 对绿光敏感，约 32% 对红光敏感，约 2% 对蓝光敏感。
 *   所以 Bayer 把一半像素给绿色，模仿人眼的光谱敏感度分布。
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 三、.raw 文件的磁盘存储格式（重点！）
 * ───────────────────────────────────────────────────────────────────────────
 *
 * 这就是你问的核心问题：Bayer Raw 文件里实际存放的是什么？
 *
 * 【答案】：就是一个连续的字节序列，每个字节存储一个像素的亮度值。
 *
 * 一张 640×480 的 Bayer Raw 文件大小 = 640 × 480 × 1 字节 = 307,200 字节。
 *
 * 内存/磁盘布局（逐行存储，行内从左到右）：
 *
 *   字节偏移      存储内容                    对应的像素位置
 *   ─────────────────────────────────────────────────────────────
 *   offset 0  →  R 的值 (0~255)             ← 第0行第0列，红色像素
 *   offset 1  →  G 的值 (0~255)             ← 第0行第1列，绿色像素(Gr)
 *   offset 2  →  R 的值 (0~255)             ← 第0行第2列，红色像素
 *   offset 3  →  G 的值 (0~255)             ← 第0行第3列，绿色像素(Gr)
 *   ...       →  ...                        ← 第0行其余像素
 *   offset 640   →  G 的值 (0~255)          ← 第1行第0列，绿色像素(Gb)
 *   offset 641   →  B 的值 (0~255)          ← 第1行第1列，蓝色像素
 *   offset 642   →  G 的值 (0~255)          ← 第1行第2列，绿色像素(Gb)
 *   offset 643   →  B 的值 (0~255)          ← 第1行第3列，蓝色像素
 *   ...       →  ...                        ← 第1行其余像素
 *   offset 1280  →  R 的值 (0~255)          ← 第2行第0列，红色像素
 *   ...       →  ...                        ← 以此类推
 *   offset 307199 → B 的值 (0~255)          ← 最后一行最后一列
 *
 * 【关键理解】：文件本身不记录"这个像素是什么颜色"！
 *   颜色信息不在文件里，而是在"你怎么解读这些字节"的规则里。
 *   规则就是 Bayer Pattern（RGGB），你必须提前知道图像的宽高和 Bayer 排列方式，
 *   才能正确地把每个字节对应到正确的颜色通道。
 *
 * 对比 RGB 文件（如 03_demosaic_linear_rgb24.raw）：
 *   - Bayer Raw:  每像素 1 字节，文件大小 = W × H × 1
 *   - RGB24 Raw:  每像素 3 字节 (R,G,B交织)，文件大小 = W × H × 3
 *
 *   示例：一个 640×480 的图像
 *     Bayer Raw 大小 = 640 × 480 × 1 =   307,200 字节
 *     RGB Raw  大小 = 640 × 480 × 3 =   921,600 字节（3倍大！）
 *
 * ╔═══════════════════════════════════════════════════════════════════════════╗
 * ║  ★ 常见误区：为什么 Bayer Raw 文件大小 = W×H，而不是 W×H×4？              ║
 * ║    "RGGB 四个值组成一个彩色像素，不应该每个像素占 4 字节吗？"               ║
 * ╚═══════════════════════════════════════════════════════════════════════════╝
 *
 * 这是几乎每个初学者都会产生的困惑。让我用一个具体的例子来澄清。
 *
 * 你的推理路径：
 *   "一个彩色像素 = R + G + G + B 四个子像素 → 每个像素4个亮度值 → 640×480的
 *    图像应该有 640×480×4 = 1,228,800 个亮度值"
 *
 * 这个推理的 bug 在于：你把 "Bayer 2×2 排列单元" 当作了 "一个像素"。
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 关键概念：Sensor 上的每一个感光单元本身就是"一个像素"
 * ───────────────────────────────────────────────────────────────────────────
 *
 * 在 Bayer Sensor 上，每个微小的感光单元（photosite）就是一个独立的像素。
 * 它上面盖了什么颜色的滤镜，它就负责测量那种颜色在这个位置上的光强。
 *
 * 所以：
 *
 *   术语                     在物理传感器上的含义           在数据中的体现
 *   ─────────────────────────────────────────────────────────────────────
 *   "一个感光单元/photosite"   一个光电二极管 + 一个彩色滤镜   1 个字节
 *   "一个 Bayer 像素"         同上，就是一个感光单元          1 个字节
 *   "传感器分辨率 640×480"    有 640 列 × 480 行 个感光单元   640×480 个字节
 *
 *   一个感光单元 ≠ 一个"RGGB 组"
 *   一个感光单元 = 一个 Bayer 像素 = 一个字节
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 用图说明：Bayer Sensor 上的像素粒度
 * ───────────────────────────────────────────────────────────────────────────
 *
 * 假设传感器是 6×4（宽6，高4），共 24 个感光单元：
 *
 *   列:  0     1     2     3     4     5
 *        ↓     ↓     ↓     ↓     ↓     ↓
 *   行0 [R00] [G01] [R02] [G03] [R04] [G05]    ← 6 个感光单元，6 个字节
 *   行1 [G10] [B11] [G12] [B13] [G14] [B15]    ← 6 个感光单元，6 个字节
 *   行2 [R20] [G21] [R22] [G23] [R24] [G25]    ← 6 个感光单元，6 个字节
 *   行3 [G30] [B31] [G32] [B33] [G34] [B35]    ← 6 个感光单元，6 个字节
 *
 *   总共：24 个感光单元 = 24 个 Bayer 像素 = 24 字节
 *
 * 如果你把 "RGGB" 四个感光单元当作一个像素，那么：
 *
 *   6×4 的传感器 = (6/2) × (4/2) = 3×2 = 6 个 "RGGB 组"
 *   每组 4 个字节 → 6 × 4 = 24 字节
 *
 *   结果完全一样！24 字节。
 *
 * 为什么？因为：
 *   - 按感光单元算：W × H 个像素 × 1 字节/像素 = W×H 字节
 *   - 按 RGGB 组算：(W/2) × (H/2) 个组 × 4 字节/组 = (W×H/4) × 4 = W×H 字节
 *
 * 两种理解方式的文件大小是一样的！你之所以觉得应该是 4 倍，是因为你以为
 * "RGGB 组"的数量等于像素数量。但实际上，RGGB 组的数量只有像素数量的 1/4。
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 那 "RGGB 四个值组成一个颜色" 到底是什么意思？
 * ───────────────────────────────────────────────────────────────────────────
 *
 * 这是去马赛克（demosaicing）做的事情，不是传感器做的事情！
 *
 * 传感器（硬件层）：                      去马赛克（软件层）：
 *   每个感光单元只记录 1 个字节              用周围像素的值"猜"出缺失的颜色
 *                                         每个感光单元位置 → 补全为 3 字节 RGB
 *
 *   输入：640×480 个独立字节               输入：640×480 个独立字节
 *   输出：640×480 × 1 = 307,200 字节      输出：640×480 × 3 = 921,600 字节
 *   （每像素1个颜色）                      （每像素3个颜色，通过插值生成）
 *
 * 去马赛克不会改变图像的分辨率！
 *   输入是 640×480 个感光单元 → 输出是 640×480 个 RGB 像素，分辨率不变。
 *   只是每个位置从 "一种颜色" 变成了 "三种颜色（插值补全）"。
 *
 * 用一个具体的感光单元位置来理解（以 RGGB 为例）：
 *
 *   传感器上位置 (0,0) 的感光单元，盖了 R 滤镜：
 *     → Raw 文件中存了 1 个字节：该位置的 R 光强值
 *     → 但该位置的 G 和 B 光强值是多少？传感器没测！
 *     → 去马赛克用周围像素来"猜"：G 取上下左右的 G 像素平均，B 取对角 B 平均
 *     → 最终输出：(0,0) 位置有 [R真实, G插值, B插值] 三个字节
 *
 *   传感器上位置 (1,1) 的感光单元，盖了 B 滤镜：
 *     → Raw 文件中存了 1 个字节：该位置的 B 光强值
 *     → 去马赛克后补全为 [R插值, G插值, B真实]
 *
 * 所以 "RGGB 四合一" 不是传感器做的，是去马赛克算法"脑补"出来的！
 * 每个感光单元最终都会成为一个独立的 RGB 像素，不会四合一。
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 一句话总结
 * ───────────────────────────────────────────────────────────────────────────
 *
 *   Bayer Raw 文件大小 = W × H × 1 字节（每个感光单元一个字节，物理上就是这么多）
 *   去马赛克后 RGB 大小 = W × H × 3 字节（每个位置补全为三个颜色通道）
 *   分辨率始终是 W × H，不会变成 (W/2) × (H/2)！
 *
 * ╔═══════════════════════════════════════════════════════════════════════════╗
 * ║  ★ 追问：Bayer Raw 的像素排列和 RGB 格式是一一对应的吗？                    ║
 * ║     "如果把 Bayer 理解成 '粗略的 W×H/4 画面'，对吗？"                      ║
 * ╚═══════════════════════════════════════════════════════════════════════════╝
 *
 * 这是一个非常好的后续追问。让我分两层来回答。
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 第一层：空间位置上 —— 是的，一一对应
 * ───────────────────────────────────────────────────────────────────────────
 *
 * Bayer Raw 的感光单元与输出 RGB 的像素在空间上是 1:1 对应的。
 *
 *   Bayer Raw[0][0]（R滤镜感光单元）→ 去马赛克 → RGB[0][0]（完整的 R,G,B 值）
 *   Bayer Raw[0][1]（G滤镜感光单元）→ 去马赛克 → RGB[0][1]（完整的 R,G,B 值）
 *   Bayer Raw[0][2]（R滤镜感光单元）→ 去马赛克 → RGB[0][2]（完整的 R,G,B 值）
 *   ...
 *
 * 位置不移动、不合并。感光单元 (x,y) 就变成输出像素 (x,y)。
 * 排列完全一致，分辨率不变。
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 第二层："W×H/4 的有效分辨率"这个直觉对吗？—— 对了一半
 * ───────────────────────────────────────────────────────────────────────────
 *
 * 你的直觉 "Bayer 只有 1/4 的彩色信息" 在色度分辨率（chroma resolution）
 * 的意义上是正确的，但需要精确理解：
 *
 *   分辨率类型            Bayer Raw 能提供的信息          说明
 *   ───────────────────────────────────────────────────────────────────
 *   亮度分辨率 (Luma)     ≈ W × H                        绿色占 50%，
 *   空间分辨率 (Spatial)  ≈ W × H                        R 和 B 位置也能感知亮度变化
 *   红色色度分辨率        ≈ (W/2) × (H/2)               只有 1/4 的感光单元是 R
 *   蓝色色度分辨率        ≈ (W/2) × (H/2)               只有 1/4 的感光单元是 B
 *   绿色色度分辨率        ≈ W × H / 2                    有一半的感光单元是 G
 *
 * 这意味着：
 *
 *   - 如果你拍一张黑白条纹的图（只测亮度），Bayer 几乎能达到 W×H 的分辨率。
 *     因为每个感光单元（不管什么颜色）都能感知亮度变化。
 *
 *   - 如果你拍一张红蓝条纹的图（只测色彩细节），Bayer 的有效彩色分辨率大约
 *     只有 (W/2)×(H/2)。因为 R 感光单元之间的间距是 2 像素，B 也是。
 *
 *   这就是为什么你用 Bayer Raw 直接看（不经过任何处理），会看到：
 *     - 边缘和纹理很清晰（亮度信息密集）
 *     - 但纯色区域有网格感（颜色信息稀疏）
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 一个直观的比喻：电影院座位 vs 电影院灯光
 * ───────────────────────────────────────────────────────────────────────────
 *
 * 想象一个 10×10 的电影院，每个座位扶手上有三种小灯：红、绿、蓝。
 *
 *   真正的 RGB 显示：
 *     每个座位都有 [红灯 绿灯 蓝灯] 三个灯同时亮
 *     → 每个座位都是一个完整的彩色像素
 *     → 10×10 = 100 个完整像素
 *
 *   Bayer Sensor：
 *     座位按 RGGB 模式每个座位只装了一种颜色的灯：
 *       座位(0,0)=红灯, 座位(0,1)=绿灯, 座位(0,2)=红灯, 座位(0,3)=绿灯, ...
 *       座位(1,0)=绿灯, 座位(1,1)=蓝灯, 座位(1,2)=绿灯, 座位(1,3)=蓝灯, ...
 *     → 每个座位只有一种颜色的灯
 *     → 但每个座位仍然是一个"测量点"
 *     → 去马赛克 = 看周围座位灯的颜色，猜这个座位如果三种灯都有，各应该多亮
 *     → 最终 10×10 = 100 个完整像素（不是 5×5 = 25 个！）
 *
 * 所以：
 *   "粗略的 W×H/4 感光面积" ← 不对，空间感光面积就是 W×H
 *   "粗略的 W×H/4 彩色信息" ← 部分对，R 和 B 通道各只有 W×H/4 个真实采样点
 *                            （但 G 有 W×H/2 个，亮度有 W×H 个）
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 排列一致性的最终答案
 * ───────────────────────────────────────────────────────────────────────────
 *
 *   Bayer Raw 像素 (x,y) ←→ 去马赛克后 RGB 像素 (x,y)  ←→  显示器上像素 (x,y)
 *
 *   三者的空间排列是完全一致的！不存在"四个 Bayer 像素合并为一个 RGB 像素"。
 *   每个 Bayer 感光单元各自独立地成为一个 RGB 像素，缺失的颜色通过插值补全。
 *
 * 这也是为什么 Bayer Raw 是传感器的"原生"输出 —— 在同样的带宽下，
 * 可以传输更高分辨率的图像（因为只传 1/3 的数据量）。
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 四、用 C 语言理解 Bayer Raw 的内存访问
 * ───────────────────────────────────────────────────────────────────────────
 *
 * 假设你有一个 uint8_t *bayer 指向 Bayer Raw 数据，宽 = width，高 = height：
 *
 *   // 访问第 y 行、第 x 列的像素值（亮度值，0~255）：
 *   uint8_t pixel_value = bayer[y * width + x];
 *
 *   // 判断这个像素是什么颜色（RGGB 模式）：
 *   if ((y & 1) == 0) {          // 偶数行
 *       if ((x & 1) == 0)         // 偶数列 → R
 *           printf("这是 R 像素，值 = %d\n", pixel_value);
 *       else                      // 奇数列 → G
 *           printf("这是 G 像素，值 = %d\n", pixel_value);
 *   } else {                     // 奇数行
 *       if ((x & 1) == 0)         // 偶数列 → G
 *           printf("这是 G 像素，值 = %d\n", pixel_value);
 *       else                      // 奇数列 → B
 *           printf("这是 B 像素，值 = %d\n", pixel_value);
 *   }
 *
 * 这就是为什么在 ISP 处理中，你总是在看到 (y & 1) 和 (x & 1) 的判断 ——
 * 它们就是在根据坐标推断 Bayer 像素的颜色！
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 五、带黑电平的 Bayer Raw（更接近真实传感器）
 * ───────────────────────────────────────────────────────────────────────────
 *
 * 在真实的相机传感器中，像素值不是从 0 开始的！
 *
 * 传感器即使在完全黑暗的条件下，模拟电路也会输出一个微小的偏移电压，
 * 这导致 ADC 转换后的数字值有一个基础偏移量，叫做"黑电平"（black level）。
 *
 * 例如 black_level = 64（在 8-bit 模式下常见）：
 *
 *   物理光线情况         传感器输出电压    ADC 转换后的值    存储的字节值
 *   ──────────────────────────────────────────────────────────────────
 *   完全黑暗（无光）     基础暗电流         约 64             64
 *   极暗                 暗电流 + 微弱信号  约 68~72          68~72
 *   正常亮度             正常信号           约 100~200        100~200
 *   非常亮（接近饱和）    接近满阱           约 255            255
 *
 * 所以 Bayer Raw 文件中 byte = 64 的那个像素，实际上应该被解读为"黑色"（值为0），
 * 而不是"深灰"（值为64）。这就是为什么 Phase 1（黑电平校正）要把值减去 black_level。
 *
 * 本程序中 black_level 的默认值是 64。
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 六、本函数的作用
 * ───────────────────────────────────────────────────────────────────────────
 *
 * generate_extreme_sensor_raw 做的是"逆向工程"：
 *   输入: 一张正常 RGB 图片（每个像素有完整的 R、G、B 值）
 *   输出: 一份 Bayer Raw 数据（每个像素只有一个颜色通道的值）
 *
 * 过程：
 *   1. 对每个像素位置，从 RGB 原图中取出 R、G、B 三个值
 *   2. 根据该像素在 Bayer Pattern 中的位置，只保留对应的那个通道的值
 *      （偶数行偶列 → 只取R，奇数行奇列 → 只取B，其他 → 只取G）
 *   3. 丢弃另外两个通道的值（模拟滤镜的遮挡效果）
 *   4. 可选：加入各种传感器缺陷（暗角、通道衰减、行列偏差等）
 *   5. 加上黑电平偏移
 *
 * 这样生成的 Bayer Raw 数据，模拟了真实图像传感器在一瞬间的输出。
 *
 * 这些模拟的缺陷包括：
 *   1. 通道增益差异   — 不同颜色通道的灵敏度不同
 *   2. 径向衰减（暗角） — 图像边缘比中心暗（vignetting）
 *   3. 行列噪声偏差   — 传感器每一行/列有微小的灵敏度差异
 *   4. 黑电平偏移     — 传感器即使完全黑暗也有基础电压输出
 */
static int generate_extreme_sensor_raw(const Config *cfg)
{
    // 计算需要的缓冲区大小
    const size_t rgb_size = (size_t)cfg->width * (size_t)cfg->height * 3u;   // RGB: 每像素3字节
    const size_t bayer_size = (size_t)cfg->width * (size_t)cfg->height;      // Bayer: 每像素1字节

    // 读取基准 RGB 原图
    uint8_t *rgb = read_file_exact(cfg->base_rgb_path, rgb_size);
    uint8_t *out;
    int x;
    int y;

    // 伪影强度（确保非负）
    float strength = clamp_non_negative(cfg->artifact_strength);

    if (!rgb)
        return -1;

    // 分配 Bayer 输出缓冲区（宽 × 高 × 1 字节）
    out = (uint8_t *)malloc(bayer_size);
    if (!out) {
        free(rgb);
        fprintf(stderr, "Out of memory generating extreme sensor raw\n");
        return -1;
    }

    /*
     * 逐像素处理：模拟传感器将 RGB 光信号转换为 Bayer Raw 信号的过程
     *
     * 核心思路：
     *   for 每一行 (y):
     *     for 每一列 (x):
     *       1. 计算归一化坐标（中心为 (0,0)，左上为 (-1,-1)，右下为 (1,1)）
     *       2. 根据到中心的距离计算每个通道的增益衰减（模拟镜头暗角）
     *       3. 加上行列偏差（模拟传感器制造差异）
     *       4. 根据 Bayer 位置决定当前像素是 R、G 还是 B
     *       5. 加上黑电平偏移
     */
    for (y = 0; y < cfg->height; ++y) {
        // ny: 归一化纵坐标，范围 [-1, 1]，图像中点 = 0
        float ny = (2.0f * (float)y / (float)(cfg->height - 1)) - 1.0f;

        for (x = 0; x < cfg->width; ++x) {
            // ---- 计算像素索引 ----
            // rgb_idx: 在 RGB 交错数组中的位置（R=+0, G=+1, B=+2）
            const size_t rgb_idx = ((size_t)y * (size_t)cfg->width + (size_t)x) * 3u;
            // out_idx: 在 Bayer 输出中的位置（每像素只有1字节）
            const size_t out_idx = (size_t)y * (size_t)cfg->width + (size_t)x;

            // ---- 计算归一化坐标 ----
            float nx = (2.0f * (float)x / (float)(cfg->width - 1)) - 1.0f;

            // ---- 计算到图像中心距离的平方（用于模拟径向衰减/暗角） ----
            // radius2 范围 [0, 1]，0=中心，1=最远的角落
            // * 0.5 是因为 (1² + (-1)²) / 2 = 1，保证角落的半径平方恰好为 1
            float radius2 = (nx * nx + ny * ny) * 0.5f;

            // ---- 取出原始 RGB 值并归一化到 [0, 1] ----
            float r = (float)rgb[rgb_idx + 0] / 255.0f;
            float g = (float)rgb[rgb_idx + 1] / 255.0f;
            float b = (float)rgb[rgb_idx + 2] / 255.0f;

            // ---- 声明后面要用到的各种变量 ----
            float sample;
            float r_gain, g_gain, b_gain;  // 各通道增益
            float row_bias, col_bias;        // 行列偏差
            // 水平和垂直方向的归一化坐标 [0, 1]（左上=0, 右下=1）
            float x_norm = (float)x / (float)(cfg->width - 1);
            float y_norm = (float)y / (float)(cfg->height - 1);

            // 限制半径平方不超过 1（理论上不会超过，但防御性编程）
            if (radius2 > 1.0f)
                radius2 = 1.0f;

            /*
             * ---- 计算各通道的增益衰减 ----
             *
             * 真实传感器的不同颜色通道灵敏度不同（因为滤镜透光率和光电转换效率差异）。
             * 这里用不同的系数模拟这种差异：
             *
             * r_gain: 红色通道增益
             *   - (1.0 - 0.78*strength): 基准衰减（红色通常灵敏度偏高）
             *   - (1.0 - 0.68*strength*radius2): 径向衰减（离中心越远越暗）
             *
             * g_gain: 绿色通道增益
             *   - (1.0 - 0.42*strength): 绿色常用作亮度基准，衰减较小
             *
             * b_gain: 蓝色通道增益
             *   - (1.0 - 0.05*strength): 蓝色在传感器上通常衰减最小
             *
             * strength=0 时所有增益=1，不做任何修改
             * strength=1 时效果最强
             */
            r_gain = (1.0f - 0.78f * strength) * (1.0f - 0.68f * strength * radius2);
            g_gain = (1.0f - 0.42f * strength) * (1.0f - 0.48f * strength * radius2);
            b_gain = (1.0f - 0.05f * strength) * (1.0f - 0.22f * strength * radius2);

            /*
             * ---- 行列偏差 ----
             *
             * 真实传感器每行/每列的读出电路可能有微小的差异，
             * 导致某些行偏亮、某些列偏暗。
             *
             * y_norm=0（顶行）时 row_bias = 1.0-0.12*strength (偏暗),
             * y_norm=1（底行）时 row_bias = 1.0+0.06*strength (偏亮)
             * 模拟了从上到下的线性渐变的灵敏度差异
             */
            row_bias = 1.0f + strength * (-0.12f + 0.18f * y_norm);
            col_bias = 1.0f + strength * (-0.10f + 0.16f * x_norm);

            // ---- 施加增益和偏差到 RGB 值 ----
            r *= r_gain * row_bias;
            g *= g_gain * col_bias;
            b *= b_gain * (1.0f - 0.04f * strength * radius2);

            /*
             * ---- Bayer 采样：每个位置只取一种颜色 ----
             *
             * 根据 RGGB 模式决定当前像素取 R、G 还是 B：
             *
             *   (y&1)==0（偶数行）:
             *     (x&1)==0（偶数列）→ R 像素
             *     (x&1)==1（奇数列）→ G 像素
             *   (y&1)==1（奇数行）:
             *     (x&1)==0（偶数列）→ G 像素
             *     (x&1)==1（奇数列）→ B 像素
             *
             * 这就是 RGGB Bayer Pattern 的排列规则！
             */
            if ((y & 1) == 0)
                sample = (x & 1) == 0 ? r : g;  // 偶数行：偶列R，奇列G
            else
                sample = (x & 1) == 0 ? g : b;  // 奇数行：偶列G，奇列B

            /*
             * ---- 施加黑电平偏移 ----
             *
             * 传感器的模拟电路即使在完全黑暗的情况下也会输出一个微小的电压，
             * 这个基础值就叫做"黑电平"（black level）。
             *
             * 对于 8-bit 数据，black_level=64 意味着：
             *   有效范围从 64~255 压缩到 0~255，
             *   64 以下的都是噪声，真实的黑应该在 64 的位置。
             *
             * 公式：output = black_level + sample * (255 - black_level)
             * 效果：sample=0 → output=64（黑）, sample=1 → output=255（白）
             */
            out[out_idx] = clamp_u8((float)cfg->black_level + sample * (255.0f - (float)cfg->black_level));
        }
    }

    // 将生成的 Bayer Raw 数据写入文件
    if (write_file(cfg->generated_bayer_path, out, bayer_size) != 0) {
        free(out);
        free(rgb);
        return -1;
    }

    printf("Generated extreme Bayer raw: %s\n", cfg->generated_bayer_path);

    free(out);
    free(rgb);
    return 0;
}

/* ====================================================================
 * ╔═══════════════════════════════════════════════════════════════════╗
 * ║                 第 3 部分：ISP Pipeline 各阶段                       ║
 * ║              （真正的"图像处理流水线"）                                ║
 * ╚═══════════════════════════════════════════════════════════════════╝
 *
 * Pipeline 的数据流：
 *
 *   sensor_u8 (Bayer, uint8_t)
 *       │
 *       ▼  subtract_black_level()           ← 阶段1: 黑电平校正
 *   black_plane (Bayer, float [0~1])
 *       │
 *       ▼  apply_lsc_and_wb()               ← 阶段2: 镜头阴影校正 + 白平衡
 *   lsc_wb_plane (Bayer, float [0~1])
 *       │
 *       ▼  demosaic_and_finish()            ← 阶段3: 去马赛克 + CCM + 饱和度 + Gamma
 *   linear_rgb (RGB, uint8_t) ── 去马赛克后的线性 RGB（无 Gamma，可直接看到效果）
 *   display_rgb (RGB, uint8_t) ── 完整处理后适合显示的 RGB
 *       │
 *       ▼  rgb_to_yuv420p()                 ← 阶段4: 色彩空间转换
 *   display_yuv (YUV 4:2:0) ── 适合视频编码的格式
 *
 * 每个阶段的输出都会被保存，你可以看到：
 *   00_sensor_mosaic.*   — 原始 Bayer 数据（阶段0：输入）
 *   01_black_level.*     — 黑电平校正后（阶段1）
 *   02_lsc_wb.*          — LSC + 白平衡后（阶段2）
 *   03_demosaic_linear.* — 去马赛克后的线性 RGB（阶段3.1）
 *   04_display.*         — 完整处理后 RGB（阶段3.2）
 *   05_display_yuv420p.* — YUV 4:2:0 格式（阶段4）
 * ==================================================================== */

/*
 * ====================================================================
 * 阶段 1: 黑电平校正 (Black Level Correction)
 * ====================================================================
 *
 * 【什么是黑电平？】
 * 传感器像素读出电路的基准电压不是 0V。即使将传感器置于完全黑暗的环境，
 * ADC（模数转换器）输出的数字值也不是 0，而是一个小的正数（比如 64）。
 * 这个偏移量就是"黑电平"。
 *
 * 【为什么需要校正？】
 * 如果不减去黑电平，整个图像会偏灰偏亮，真正的黑色变成灰色，
 * 后续的白平衡和颜色校正也算不准。
 *
 * 【算法】
 * 对于每个像素：
 *   corrected[i] = (raw[i] - black_level) / (255 - black_level)
 *
 * 这样，原始值等于 black_level 的像素 → 校正后为 0（纯黑）
 *       原始值等于 255 的像素      → 校正后为 1（纯白）
 *
 * 输出从 uint8_t (0~255 整数) 转为 float (0.0~1.0 浮点数)，
 * 这是为了后续计算的精度 —— 浮点数多次乘除不会累积舍入误差。
 */
static void subtract_black_level(const uint8_t *raw, float *out, int count, int black_level)
{
    int i;
    // 计算缩放因子：将 [black_level, 255] 映射到 [0, 1]
    // 如果 black_level=64，则 scale = 1/(255-64) ≈ 0.00524
    float scale = 1.0f / (float)((255 - black_level) > 0 ? (255 - black_level) : 1);

    for (i = 0; i < count; ++i)
        out[i] = clamp01(((float)raw[i] - (float)black_level) * scale);
}

/*
 * ====================================================================
 * 阶段 2: 镜头阴影校正 (LSC) + 白平衡 (WB)
 * ====================================================================
 *
 * 这个函数同时做了两件事（因为它们都是对 Bayer 数据的逐像素乘法操作，
 * 合并到一起可以减少遍历次数，提高效率）。
 *
 * ── 2.1 镜头阴影校正 (Lens Shading Correction, LSC) ──
 *
 * 【问题】镜头的光学特性导致图像边缘比中心暗（"暗角"或 vignetting）。
 *        另外，不同颜色通道的衰减程度可能不同（色差暗角）。
 *
 * 【解决方案】根据像素到图像中心的距离，施加一个补偿增益：
 *           离中心越远，增益越大（提亮更多）。
 *
 *   增益公式：lsc_gain = 1.0 + lsc_strength × radius²
 *
 *   其中 radius² 是像素到图像中心距离的平方（已归一化到 [0,1]）。
 *   中心 radius²=0 → gain=1（不变）
 *   角落 radius²=1 → gain=1+lsc_strength（提亮）
 *   lsc_strength 越大，边缘补偿越强。
 *
 * ── 2.2 白平衡 (White Balance, WB) ──
 *
 * 【问题】不同光源（晴天、阴天、白炽灯）的色温不同，导致白色物体拍出来偏黄或偏蓝。
 *
 * 【解决方案】对 R、G、B 通道分别乘以不同的增益，让白色物体在图像中确实是白色。
 *
 *   在白炽灯下（偏黄/红）：
 *     → wb_r 较小（压低红色），wb_b 较大（增强蓝色）
 *   在阴天下（偏蓝）：
 *     → wb_r 较大，wb_b 较小
 *
 * 注意：对 Bayer 数据来说，需要知道每个像素的位置对应什么颜色，
 *       再施加对应的白平衡增益。规则和 Bayer Pattern 一致：
 *       - 偶数行偶数列 → R 像素 → 乘 wb_r
 *       - 奇数行奇数列 → B 像素 → 乘 wb_b
 *       - 其他位置     → G 像素 → 乘 wb_g
 */
static void apply_lsc_and_wb(const float *plane, float *out, const Config *cfg)
{
    int x;
    int y;
    // 图像最大索引（用于归一化坐标计算）
    float w_max = (float)(cfg->width - 1);
    float h_max = (float)(cfg->height - 1);

    for (y = 0; y < cfg->height; ++y) {
        // 归一化纵坐标，范围 [-1, 1]，0=图像中心
        float ny = (2.0f * (float)y / h_max) - 1.0f;

        for (x = 0; x < cfg->width; ++x) {
            size_t idx = (size_t)y * (size_t)cfg->width + (size_t)x;

            // 归一化横坐标
            float nx = (2.0f * (float)x / w_max) - 1.0f;

            // 到图像中心距离的平方，范围 [0, 1]
            float radius2 = (nx * nx + ny * ny) * 0.5f;

            float lsc_gain;   // LSC 增益
            float color_gain; // WB 增益（根据当前像素的颜色通道选取）

            if (radius2 > 1.0f)
                radius2 = 1.0f;

            // ---- LSC 增益：离中心越远，增益越大 ----
            lsc_gain = 1.0f + cfg->lsc_strength * radius2;

            // ---- WB 增益：根据 Bayer 位置选择对应的白平衡增益 ----
            if ((y & 1) == 0 && (x & 1) == 0)
                color_gain = cfg->wb_r;       // 偶行偶列 → R
            else if ((y & 1) == 1 && (x & 1) == 1)
                color_gain = cfg->wb_b;       // 奇行奇列 → B
            else
                color_gain = cfg->wb_g;       // 其他 → G（在 RGGB 模式下占 50% 像素）

            // 施加 LSC 和 WB 增益，并 clamp 到 [0,1]
            out[idx] = clamp01(plane[idx] * lsc_gain * color_gain);
        }
    }
}

/*
 * sample_plane —— 从浮点图像平面采样一个像素值（带边界处理）
 *
 * 当去马赛克算法需要取邻近像素时，边缘像素可能"越界"。
 * 这个函数用 "clamp to edge" 策略处理边界：
 *   如果 x<0，返回 x=0 处的值（左边缘）
 *   如果 x>=width，返回 x=width-1 处的值（右边缘）
 *   y 同理
 *
 * 这是图像处理中最常用的边界处理方式之一。
 */
static float sample_plane(const float *plane, int width, int height, int x, int y)
{
    // 边界 clamp：将坐标限制在有效范围内
    if (x < 0)
        x = 0;
    else if (x >= width)
        x = width - 1;

    if (y < 0)
        y = 0;
    else if (y >= height)
        y = height - 1;

    // 一维索引：把二维坐标 (x,y) 转换为一维数组下标
    // 内存布局是逐行存储的：第0行、第1行、...、第 height-1 行
    return plane[(size_t)y * (size_t)width + (size_t)x];
}

/*
 * ====================================================================
 * 阶段 3: 去马赛克 (Demosaicing) + 颜色校正矩阵 (CCM) + 饱和度 + Gamma 校正
 * ====================================================================
 *
 * 这是 ISP Pipeline 中最复杂的一个阶段，包含了四个子步骤。
 * 合并在一起可以避免多次遍历图像，提高缓存命中率和执行效率。
 *
 * ╔═══════════════════════════════════════════════════════════════════════════╗
 * ║  Bayer Raw vs RGB24 —— 两种格式存储"颜色亮度值"的本质区别                  ║
 * ╚═══════════════════════════════════════════════════════════════════════════╝
 *
 * 在理解去马赛克之前，必须先搞清楚：输入格式 (Bayer Raw) 和输出格式 (RGB24)
 * 在存储"颜色和亮度"上有什么本质不同。
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 对比一：每像素存储的字节数
 * ───────────────────────────────────────────────────────────────────────────
 *
 *   Bayer Raw（阶段0~2）              RGB24（阶段3 之后）
 *   ─────────────────────             ──────────────────────
 *   每像素 = 1 字节                    每像素 = 3 字节
 *   一张 640×480 = 307,200 字节         一张 640×480 = 921,600 字节（3倍！）
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 对比二：每个字节存的到底是什么？
 * ───────────────────────────────────────────────────────────────────────────
 *
 *   Bayer Raw（以 RGGB 为例）                  RGB24
 *   ────────────────────────────              ─────────────────────────
 *
 *   设我们看第 y 行第 x 列的像素：
 *
 *   Bayer:                                   RGB:
 *   offset = y * width + x                   offset = (y * width + x) * 3
 *   这里只有 1 个字节！                       这里有 3 个连续的字节！
 *
 *                                             offset + 0 = R（红色通道的亮度值）
 *   [ 200 ]  ← 这个数字只代表                    offset + 1 = G（绿色通道的亮度值）
 *              "R的光强" 或 "G的光强"             offset + 2 = B（蓝色通道的亮度值）
 *              或 "B的光强"，取决于
 *              该位置的 Bayer 排列。             例：
 *                                              [ 180, 95, 42 ]
 *   它到底代表什么颜色？                            ↑    ↑    ↑
 *   不能从字节本身判断！                           R值  G值  B值
 *   必须结合 (x,y) 坐标 +
 *   Bayer Pattern 规则才能知道。               每个像素都拥有完整的三个通道！
 *                                             可以直接知道这个像素的
 *                                             颜色和亮度。
 *
 * 关键结论（这是从 Bayer 到 RGB 最核心的思维转变）：
 *
 *   ┌──────────────────────────────────────────────────────────────────┐
 *   │                                                                  │
 *   │  Bayer Raw:  每个字节 = "某个颜色的亮度"，但颜色要查坐标才能确定      │
 *   │  RGB24:      每个字节 = "某个固定通道的亮度值"，颜色信息内嵌在位置中  │
 *   │                                                                  │
 *   │  Bayer 的字节是"匿名"的（看不出什么颜色），                          │
 *   │  RGB 的字节是"具名"的（R就是R，G就是G，B就是B）                     │
 *   │                                                                  │
 *   └──────────────────────────────────────────────────────────────────┘
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 对比三：同一个物理场景，两种格式怎么记录？
 * ───────────────────────────────────────────────────────────────────────────
 *
 * 假设传感器拍摄到一个"纯黄色"的像素区域。
 * 在自然界中，黄色光 = 红光 + 绿光（没有蓝光）。
 *
 * 如果这个黄色的亮度是 R=200, G=180, B=0：
 *
 *   在 Bayer Raw (RGGB) 中存储为：
 *
 *     位置        颜色滤镜    穿过滤镜后的光强    存储的字节值
 *     ──────────────────────────────────────────────────────
 *     (0,0)       R 滤镜       200                200
 *     (0,1)       G 滤镜       180                180
 *     (0,2)       R 滤镜       200                200
 *     (0,3)       G 滤镜       180                180
 *     (1,0)       G 滤镜       180                180
 *     (1,1)       B 滤镜         0                  0  ← 蓝光被滤镜挡住了！
 *     (1,2)       G 滤镜       180                180
 *     (1,3)       B 滤镜         0                  0
 *     ...
 *
 *   可以看到：Bayer Raw 中相邻位置的字节值差异巨大（200 ↔ 180 ↔ 0），
 *   这是因为每个位置测量的颜色通道不同，不是真实的亮度跳变！
 *
 *   在 RGB24 中存储为（经过去马赛克后，每个像素都有完整的 RGB）：
 *
 *     像素位置    R    G    B    说明
 *     ──────────────────────────────────────────
 *     (0,0)     200  180   0    ← 通过周围像素插值补全了三个通道
 *     (0,1)     200  180   0    ← 同样补全了
 *     (0,2)     200  180   0    ← 同样补全了
 *     ...       ...  ...  ...
 *
 *   可以看到：RGB24 每个像素的三个通道值都是完整的，相邻像素的值很接近
 *   （因为真实场景中颜色确实在缓慢变化）。这才是我们期望看到的"图像数据"。
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 对比四：内存布局直观对比（640×480 图像的前几个字节）
 * ───────────────────────────────────────────────────────────────────────────
 *
 *   Bayer Raw (640×480, 307,200 字节)：
 *
 *     [0]: 200  ← 像素(0,0), R 滤镜下的亮度
 *     [1]: 180  ← 像素(0,1), G 滤镜下的亮度
 *     [2]: 200  ← 像素(0,2), R 滤镜下的亮度
 *     [3]: 180  ← 像素(0,3), G 滤镜下的亮度
 *     [4]: 200  ← 像素(0,4), R 滤镜下的亮度
 *     ...        └─ 你无法从字节本身知道这是什么颜色！
 *
 *   RGB24 (640×480, 921,600 字节)：
 *
 *     [0]: 200  ← 像素(0,0) 的 R 通道 ← 明确是 R！
 *     [1]: 180  ← 像素(0,0) 的 G 通道 ← 明确是 G！
 *     [2]:   0  ← 像素(0,0) 的 B 通道 ← 明确是 B！
 *              └──── 这 3 个字节共同描述像素(0,0) 的完整颜色 ────┘
 *
 *     [3]: 200  ← 像素(0,1) 的 R 通道
 *     [4]: 180  ← 像素(0,1) 的 G 通道
 *     [5]:   0  ← 像素(0,1) 的 B 通道
 *              └──── 这 3 个字节共同描述像素(0,1) 的完整颜色 ────┘
 *     ...
 *
 *   访问公式的对比：
 *     Bayer:  pixel_value = data[y * width + x];              // 返回1个字节，需查坐标知颜色
 *     RGB24:  R = data[(y * width + x) * 3 + 0];              // 返回3个字节，位置即颜色
 *             G = data[(y * width + x) * 3 + 1];
 *             B = data[(y * width + x) * 3 + 2];
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 对比五：linear_rgb vs display_rgb（两种 RGB 的"亮度"含义不同）
 * ───────────────────────────────────────────────────────────────────────────
 *
 * 本函数同时输出两种 RGB：
 *
 *   1. linear_rgb（线性 RGB）
 *      - 去马赛克后直接得到的 RGB
 *      - 每个通道的值与物理光强度成正比（线性关系）
 *      - 暗部看起来偏暗偏黑（因为人眼不是线性的）
 *      - 用于：后续需要做线性计算的场景（如颜色校正、混合）
 *
 *   2. display_rgb（显示 RGB）
 *      - 经过了 CCM + 饱和度 + Gamma 编码
 *      - 每个通道的值已经按照显示器响应曲线做了变形
 *      - 暗部被提亮了（Gamma 校正的效果），看起来更"正常"
 *      - 用于：直接在屏幕上观看、保存为图片
 *
 *   示例：同一个像素 R 通道，物理光强度 = 0.2（20% 的亮度）：
 *
 *     linear_rgb 存储的值： 0.2 × 255 = 51              ← 存的是"物理光强度"
 *     display_rgb 存储的值：0.2^(1/2.2) × 255 ≈ 120    ← 存的是"显示器应该显示的码值"
 *
 *   两者存的是同一个像素，但字节的"含义"不同：
 *     linear_rgb 的 51  = "物理上这里只有20%的光"
 *     display_rgb 的 120 = "为了让观众感知到20%的光，显示器应该输出这个码值"
 *
 *   这就是为什么 linear_rgb 文件看起来偏暗、display_rgb 看起来正常。
 *
 * ── 3.1 去马赛克 (Demosaicing) ──
 *
 * 【问题】Bayer Raw 数据每个像素只有 R、G、B 中的一个值，缺失了另外两个。
 *        要重建完整的 RGB 图像，需要从周围的像素"猜测"缺失的颜色。
 *
 * 【算法：双线性插值 (Bilinear Interpolation)】
 *
 * 以 RGGB 为例，把 Bayer 数据分四种情况处理：
 *
 *   Bayer Pattern:        每种位置缺失什么：
 *    R  G  R  G              R 位置：缺少 G 和 B
 *    G  B  G  B              Gr 位置（R 行的 G）：缺少 R 和 B
 *    R  G  R  G              Gb 位置（B 行的 G）：缺少 R 和 B
 *    G  B  G  B              B 位置：缺少 R 和 G
 *
 *   R 位置（偶行偶列）的插值：
 *   已知：R = 当前像素值
 *     G = 上下左右 4 个邻接 G 的平均值（因为 R 的上下左右恰好都是 G）
 *     B = 对角线 4 个 B 的平均值
 *
 *     邻域示意（R 是中心像素）：
 *        R(x-1,y-1)   G(x,y-1)   R(x+1,y-1)
 *        G(x-1,y)     [R(x,y)]   G(x+1,y)
 *        R(x-1,y+1)   G(x,y+1)   R(x+1,y+1)
 *
 *     G = (G左 + G右 + G上 + G下) / 4      ← 上下左右
 *     B = (B左上 + B右上 + B左下 + B右下) / 4  ← 四个对角
 *
 *   B 位置（奇行奇列）的插值：
 *   对称于 R 位置：B 已知，用同样方式算 R 和 G。
 *
 *   Gr 位置（偶行奇列，R 行中的 G）的插值：
 *   已知：G = 当前像素值
 *     R = 左右两个相邻 R 的平均值（因为 Gr 的左右恰好是 R）
 *     B = 上下两个相邻 B 的平均值（因为 Gr 的上下恰好是 B）
 *
 *   Gb 位置（奇行偶列，B 行中的 G）的插值：
 *   已知：G = 当前像素值
 *     R = 上下两个相邻 R 的平均值
 *     B = 左右两个相邻 B 的平均值
 *
 * 双线性插值是去马赛克中最简单直观的方法。它的优点是快、易懂，
 * 缺点是会在边缘区域产生伪彩色（如拉链效应、摩尔纹）。
 *
 * ╔═══════════════════════════════════════════════════════════════════════════╗
 * ║              高级去马赛克算法简介                                          ║
 * ╚═══════════════════════════════════════════════════════════════════════════╝
 *
 * 双线性插值的问题根源在于：它把每个缺失通道独立做平均，完全忽略了通道之间
 * 的"相关性"（色差恒定假设）。高级算法正是利用这一相关性来大幅改善画质。
 * 下面介绍两种工业界广泛使用的经典算法。
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 一、Malvar-He-Cutler (MHC) 算法 —— 带梯度的线性插值
 * ───────────────────────────────────────────────────────────────────────────
 *
 * 【论文】"High-Quality Linear Interpolation for Demosaicing of
 *         Bayer-Patterned Color Images", Microsoft Research, 2004.
 *         作者：Henrique S. Malvar, Li-wei He, Ross Cutler
 *
 * 【核心思想】在双线性插值的基础上，加入"梯度校正项"。
 *
 * 双线性插值的问题是：
 *   假设 R 像素需要猜 G 值，双线性取上下左右 4 个 G 的平均。
 *   如果当前处于一条竖直边缘上，左边的 G 和右边的 G 可能差异巨大，
 *   简单平均会产生错误的绿色值，进而引发伪彩色。
 *
 * MHC 的改进：
 *   不只取 G 的平均，还要"看一眼 R 本身的变化趋势"，用来校正 G 的平均值。
 *
 *   公式（以 R 位置计算缺失的 G 为例）：
 *
 *     G_est = G_avg + alpha × (R_center - R_avg)
 *
 *     其中：
 *       G_avg    = 上下左右 4 个 G 的均值（和双线性一样）
 *       R_center = 当前 R 像素的值（已知）
 *       R_avg    = 上下左右 4 个位置的 R 的估计值（通过周围 R 的平均得到）
 *       alpha    = 一个由梯度决定的权重系数
 *
 *   直觉理解：
 *     "R_center - R_avg" 反映了当前像素的 R 值比周围"预期"的 R 值高出多少。
 *     如果 R 和 G 在边缘处同向变化（色差恒定），那么 G 也应该按比例调整。
 *     如果边缘处 R 变亮，G 大概率也变亮，所以 G_avg 需要往上修正一点。
 *
 *   梯度的作用（alpha 的计算）：
 *     alpha 不是定死的常数，而是根据水平和竖直方向的梯度来动态决定的：
 *       - 如果水平梯度大（左右差异大），说明水平方向有边缘，
 *         那么降低水平方向邻居的权重，更多依赖竖直方向
 *       - 如果竖直梯度大（上下差异大），说明竖直方向有边缘，
 *         那么降低竖直方向邻居的权重，更多依赖水平方向
 *
 *   这就是"梯度自适应"的含义：算法自动检测边缘方向，沿着边缘方向插值，
 *   避免跨越边缘插值（那会产生锯齿和伪色）。
 *
 * 【与其他算法的直观对比】
 *
 *   算法            核心策略              计算量   画质    典型伪影
 *   ─────────────────────────────────────────────────────────────────────
 *   双线性          纯空间平均             极小    差      拉链效应、摩尔纹
 *   MHC            线性 + 梯度校正         小      中      边缘轻微模糊
 *   VNG            多方向梯度投票          中      良      平坦区偶尔误判
 *   AHD            Homogeneity-directed   中      良      纹理区偶尔走样
 *   DL/ML based    CNN / Transformer      极大    优      取决于训练数据
 *
 * 【MHC 的实际地位】
 *   由于其"接近双线性的计算量 + 显著好于双线性的画质"，MHC 被广泛应用于：
 *     - 实时预览流（需要低延迟）
 *     - 嵌入式 ISP（算力有限的硬件）
 *     - 作为更高级算法的"fallback"（对极暗/极亮区域退化到 MHC）
 *   dcraw（著名的开源 RAW 解码器）也使用了一种 MHC 的变体。
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 二、VNG (Variable Number of Gradients) 算法 —— 多方向梯度投票
 * ───────────────────────────────────────────────────────────────────────────
 *
 * 【论文】"Demosaicing: Image Reconstruction from Color CCD Samples",
 *         IEEE Trans. Image Processing, 1999.
 *         作者：R. Kimmel（另一独立变体由 E. Chang 等人在同期提出）
 *         注意：dcraw 中实现的 VNG 是 Dave Coffin 综合多篇论文后的改进版。
 *
 * 【核心思想】在目标像素周围更大的邻域窗口（通常 5×5 或更大）中，
 *             沿多个方向分别计算梯度，选出"最平坦"的几个方向来做插值。
 *
 * 与 MHC 的关键区别：
 *
 *   维度            MHC                           VNG
 *   ─────────────────────────────────────────────────────────────
 *   邻域大小        3×3 或 5×5                    5×5 或更大
 *   梯度方向        仅水平和竖直（2个）             8 个方向（N, S, E, W,
 *                                                   NE, NW, SE, SW）
 *   梯度如何使用    直接作为校正系数               用来投票选出"平坦方向"
 *   权重如何分配    固定公式（由梯度算 alpha）      根据每个方向的平坦程度动态分配
 *   G 和 R/B 的    分开处理，G 用梯度校正，        统一框架，所有缺失通道都基于
 *   处理方式        R/B 用双线性                  相同的梯度判断
 *
 * 【VNG 的八个梯度方向】
 *
 * 在 5×5 的邻域中定义 8 个方向（每个方向用一个整数编号表示）：
 *
 *         NW    N    NE
 *          .    .    .
 *     W  .  [中心]  .  E
 *          .    .    .
 *         SW    S    SE
 *
 *   方向 0: N  (正北)  — 沿竖直方向往上
 *   方向 1: S  (正南)  — 沿竖直方向往下
 *   方向 2: E  (正东)  — 沿水平方向往右
 *   方向 3: W  (正西)  — 沿水平方向往左
 *   方向 4: NE (东北)  — 沿 45 度对角线往右上
 *   方向 5: NW (西北)  — 沿 45 度对角线往左上
 *   方向 6: SE (东南)  — 沿 135 度对角线往右下
 *   方向 7: SW (西南)  — 沿 135 度对角线往左下
 *
 *   对于每个方向，计算该方向上的"梯度"（沿该方向的像素值变化幅度）。
 *   梯度小的方向 = 平坦方向 = 适合插值的方向。
 *
 * 【VNG 的工作流程（以 R 像素计算缺失的 G 和 B 为例）】
 *
 *   步骤 1：计算 8 个方向的梯度
 *     - 每个方向的梯度 = 该方向上若干像素对的差的绝对值之和
 *     - 只使用与缺失通道同色的已知像素来计算梯度
 *       （例如：如果要在 R 位置算 G，就用周围已知的 G 像素来算梯度）
 *
 *   步骤 2：排除"梯度太大"的方向（非平坦方向）
 *     - 设定一个阈值（如 1.5 × 最小梯度值 或 固定值）
 *     - 梯度超过阈值的：这个方向可能跨越了边缘，不能用于插值
 *     - 剩下的"梯度够小"的方向：这些是"候选平坦方向"
 *
 *   步骤 3：用候选方向的像素值做加权平均
 *     - 对于缺失的 G：
 *       遍历所有候选平坦方向，取该方向上已知 G 像素的值
 *       权重 = 1 / (该方向的梯度 + 一个小常数)
 *       （梯度越小 -> 越平坦 -> 权重越大 -> 对最终结果的贡献越大）
 *     - 对于缺失的 B（R 位置右上角和左下角等对角位置）：
 *       同样道理，从候选平坦方向中找已知 B 像素的位置
 *
 *   步骤 4：归一化
 *     - 将所有权重的和归一化到 1.0，得到最终的加权平均
 *
 * 【VNG 的"Variable Number"（可变数量）指的是什么？】
 *
 *   这就是算法名字的由来！
 *   "Variable Number" = 参与插值的梯度方向的数量是可变的（不是固定 8 个）。
 *   一块平滑的蓝天 -> 8 个方向都很平坦 -> 8 个方向全部参与插值 -> 效果极佳
 *   一条锐利的边缘 -> 只有 2-3 个方向平坦 -> 只用这 2-3 个方向插值 -> 不越界
 *   复杂纹理区域   -> 可能只剩 1-2 个方向   -> 退化为定向插值   -> 避免伪色
 *
 * 【VNG 的优缺点】
 *
 *   优点：
 *     - 对边缘的处理比 MHC 更精细（8 方向 vs 2 方向）
 *     - 可以正确处理 45 度和 135 度对角线边缘（MHC 对此无能为力）
 *     - 在平滑区域用更多像素参与平均 -> 噪声更小
 *     - dcraw 中的实现经过了大量真实照片的验证和调优
 *
 *   缺点：
 *     - 计算量比 MHC 大约 3~5 倍（需要算 8 个梯度 + 分段筛选）
 *     - 梯度阈值是经验值，在极端情况下可能误判（如极暗噪声区域）
 *     - 5×5 邻域在图像边缘处需要更大的边界填充
 *
 * 【dcraw 中的 VNG 实现差异】
 *
 *   开源 RAW 解码器 dcraw 使用的 VNG 和原始论文有几点不同：
 *     - dcraw 把所有方向分成"梯度组"（gradient groups），
 *       而非简单的阈值二分类
 *     - dcraw 额外处理了 Gr 和 Gb 的不对称性（真实传感器中，R 行中的 G
 *       和 B 行中的 G 的灵敏度有微小差异）
 *     - dcraw 加入了对饱和像素（clipped pixel）的检测和保护，防止高光区
 *       域的错误插值扩散
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 三、本实现为何选用双线性插值
 * ───────────────────────────────────────────────────────────────────────────
 *
 * 作为一个教学演示项目，双线性插值的优势是：
 *   1. 代码只有几十行，逻辑清晰，一眼就能看懂"它在做什么"
 *   2. 不需要调任何参数（MHC 的 alpha、VNG 的梯度阈值都需要针对传感器调优）
 *   3. 执行速度最快，适合一次性处理大量教学图像
 *   4. 它产生的伪影（拉链效应、摩尔纹）恰好是理解"为什么需要更好算法"的
 *      最佳反面教材
 *
 * 如果你理解了双线性插值，再去看 MHC 和 VNG，会发现它们本质上都是
 * "在双线性的基础上，加上更聪明的像素选择 / 权重分配策略"。
 * 这也体现了 ISP 工程的演进规律：从简单平均 -> 方向自适应 -> 多方向投票 ->
 * 像素分类 -> 深度学习。
 *
 * ── 3.2 颜色校正矩阵 (Color Correction Matrix, CCM) ──
 *
 * 【问题】传感器对颜色的响应和人眼对不同波长的敏感度不完全一致。
 *        说白了，传感器"看到"的 RGB 和我们"感知"的 RGB 有偏差。
 *
 * 【解决方案】用一个 3×3 矩阵对 RGB 做线性变换：
 *
 *   [R_out]   [C11 C12 C13]   [R_in]
 *   [G_out] = [C21 C22 C23] × [G_in]
 *   [B_out]   [C31 C32 C33]   [B_in]
 *
 * 矩阵的对角线元素（C11, C22, C33）通常大于 1（增强各通道自身），
 * 非对角线元素通常为负的小数（减去其他通道的串扰）。
 *
 * 这里使用了一个预设的 base_ccm 矩阵，并通过 ccm_strength 参数
 * 控制校正强度：
 *   strength=0 → CCM = 单位矩阵（不做任何校正）
 *   strength=1 → CCM = base_ccm（完全校正）
 *   strength=2 → CCM = 过度校正（2倍效果）
 *
 * 实现方式：C_final = I + (base_ccm - I) × strength
 *   I 是单位矩阵（对角线=1，其余=0）
 *
 * ── 3.3 饱和度调整 ──
 *
 * ╔═══════════════════════════════════════════════════════════════════════════╗
 * ║                     "饱和度空间" 深度解析                                  ║
 * ╚═══════════════════════════════════════════════════════════════════════════╝
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 一、什么是"饱和度空间"？—— 一个思考颜色的框架
 * ───────────────────────────────────────────────────────────────────────────
 *
 * 严格来说，并没有一个正式的颜色空间叫"饱和度空间"。这个说法指的是
 * 一种思考颜色的方式：将 RGB 颜色分解为"亮度分量"和"色度分量"两个
 * 独立的部分，然后只操作色度分量来调整饱和度。
 *
 * 【类比：收音机的音量旋钮】
 *
 *   把一首歌想象成一个 RGB 颜色：
 *     - "音量" = 亮度（luma）：整体有多响（多亮）
 *     - "音色" = 色度（chrominance）：是什么乐器在演奏（是什么颜色）
 *     - "饱和度"旋钮 = 控制泛音的丰富程度（颜色的鲜艳程度）
 *
 *   当你拧动饱和度旋钮时：
 *     - 音量的感知不变（亮度不变）
 *     - 乐器的类型不变（色调/色相不变）
 *     - 只有音色的"纯正度"变了（饱和度变了）
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 二、几何直觉：RGB 立方体中的亮度和色度
 * ───────────────────────────────────────────────────────────────────────────
 *
 * 想象 RGB 颜色是一个 3D 空间中的立方体（每个轴是 R、G、B，范围 [0,1]）：
 *
 *        B (蓝)
 *        ↑
 *        |    黑(0,0,0)────────→ 白(1,1,1)  ← 这是"灰度对角线"
 *        |    ⁄
 *        |  ⁄
 *        |⁄
 *        └──────────→ G (绿)
 *       ⁄
 *     ⁄
 *   R (红)
 *
 * 【灰度对角线】（也叫"中性轴"或"亮度轴"）
 *   从 (0,0,0) 到 (1,1,1) 的这条线，R=G=B。
 *   这条线上的所有点都是"灰色"（没有色彩，只有亮度）。
 *
 * 【色度平面】（垂直于灰度对角线的平面）
 *   对于灰度对角线上的任意一个灰度点 L = (luma, luma, luma)，
 *   存在一个垂直于对角线的平面。这个平面上的所有点有相同的亮度，
 *   但色度和饱和度不同。
 *
 *   把 RGB 颜色 (R, G, B) 投影到灰度对角线上：
 *     投影点 = (luma, luma, luma)              ← 这就是亮度分量
 *
 *   从原点到投影点的向量 = 亮度分量（沿对角线）
 *   从投影点到原色的向量 = 色度分量（在对角线的垂直平面上）
 *
 *   数学上：
 *     RGB 颜色 = 亮度分量 + 色度分量
 *              = (luma, luma, luma) + (R-luma, G-luma, B-luma)
 *                         ↑                      ↑
 *                     沿对角线的部分          垂直于对角线的部分
 *
 *   验证色度分量是否垂直于对角线：
 *     色度 · 对角线方向 = (R-luma)+(G-luma)+(B-luma) = R+G+B - 3×luma
 *     = R+G+B - 3×(0.299R+0.587G+0.114B)
 *     = R+G+B - (0.897R+1.761G+0.342B) ≠ 0
 *   使用 BT.601 权重时不完全正交，但近似正交！
 *   如果改用 luma=(R+G+B)/3，则是精确正交。BT.601 牺牲了一点数学正交性
 *   来换取与人眼感知一致的亮度定义（绿色贡献 59% > 红色 30% > 蓝色 11%）。
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 三、本实现使用的饱和度调整公式（逐通道缩放色度分量）
 * ───────────────────────────────────────────────────────────────────────────
 *
 * 【原理】将 RGB 颜色分解为亮度 + 色度，然后按比例缩放色度分量。
 *
 *   步骤 1：计算亮度（luma）
 *     luma = 0.299×R + 0.587×G + 0.114×B
 *
 *     这个公式来自 ITU-R BT.601 标准，反映了人眼三种视锥细胞的相对密度：
 *       L 视锥（对红光敏感）≈ 30%
 *       M 视锥（对绿光敏感）≈ 59%
 *       S 视锥（对蓝光敏感）≈ 11%
 *     所以绿色对亮度的贡献最大（约 59%），红色次之（约 30%），蓝色最小（约 11%）。
 *
 *   步骤 2：计算色度分量（每个通道离"灰色"有多远）
 *     chroma_R = R - luma
 *     chroma_G = G - luma
 *     chroma_B = B - luma
 *
 *     这三个值中至少有一个 ≥ 0，至少有一个 ≤ 0。
 *     它们的加权和 ≈ 0（色度分量"近似垂直于"亮度方向）。
 *
 *   步骤 3：按比例缩放色度分量
 *     R_new = luma + saturation × chroma_R
 *     G_new = luma + saturation × chroma_G
 *     B_new = luma + saturation × chroma_B
 *
 *   saturation 参数的效果：
 *     saturation = 0   → R_new = G_new = B_new = luma（完全灰度，色度分量被清零）
 *     saturation = 1   → 保持原样
 *     saturation = 2   → 色度分量翻倍（颜色被"推离"灰度对角线 2 倍远）
 *     saturation = 0.5 → 色度分量减半（颜色向灰度靠近一半的距离）
 *
 *   ⚠️ saturation > 1 时，某些通道可能超出 [0,1] 范围，需要用 clamp01 限制。
 *   超出范围意味着该颜色在 RGB 立方体之外，clamp 会导致亮度和色相的轻微偏移
 *   （这是这个简易算法的已知缺陷）。
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 四、与正式颜色空间的对比
 * ───────────────────────────────────────────────────────────────────────────
 *
 *   颜色空间        亮度分量              色度分量              饱和度操作
 *   ──────────────────────────────────────────────────────────────────────
 *   本实现(BT.601)   luma = 0.299R+0.587   (R-luma, G-luma,     直接缩放色度
 *                    G+0.114B              B-luma)               分量
 *
 *   YCbCr (BT.601)   Y（亮度）              Cb（蓝黄色差）        需先转换到
 *                                          Cr（红青色差）        YCbCr 再缩放
 *
 *   HSL              L（明度）              S（饱和度）           直接改 S 值
 *                                          H（色相角）           （最直观）
 *
 *   HSV              V（明度）              S（饱和度）           直接改 S 值
 *                                          H（色相角）
 *
 *   YIQ (NTSC)       Y（亮度）              I（同相-橙色/青色）   需转换后再缩放
 *                                          Q（正交-紫色/黄绿）
 *
 * 本实现的方法最接近 HSL 的思路（亮度不变，仅缩放色度），但避免了
 * RGB↔HSL 的复杂三角函数转换（atan2 求色相角等），因此计算量极小。
 * 代价是：saturation 过大时 clamp 导致偏色（而真正的 HSL 不会偏色）。
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 五、为什么不在"真正的 HSL/HSV 空间"中做饱和度调整？
 * ───────────────────────────────────────────────────────────────────────────
 *
 * HSL/HSV 是操作饱和度最"正确"的颜色空间，但本实现选择了更简单的方法：
 *
 *   HSL/HSV 方案：
 *     RGB → HSL（涉及除法、atan2、条件分支）
 *     → 改 S 值
 *     → HSL → RGB（涉及更多条件分支和分段函数）
 *     计算量：约 30+ 次浮点运算 / 像素
 *
 *   本实现方案（色度分量缩放）：
 *     算 luma → 算偏差 → 缩放 → 加回
 *     计算量：约 10 次浮点运算 / 像素
 *
 *   结论：对于 ISP Pipeline 的实时处理来说，3 倍的算力差距是巨大的。
 *   在大多数场景下（saturation 在 0.8~1.3 范围内），两种方法的结果
 *   肉眼几乎看不出区别。只有极端调整（saturation > 2 或 < 0.3）时，
 *   HSL 的优势才明显。
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 六、直观理解：同一个像素在不同 saturation 下的 RGB 值变化
 * ───────────────────────────────────────────────────────────────────────────
 *
 * 假设某个像素 CCM 后的值是 (R=0.8, G=0.3, B=0.1)（偏红的橙色）：
 *
 *   luma = 0.299×0.8 + 0.587×0.3 + 0.114×0.1
 *        = 0.2392 + 0.1761 + 0.0114
 *        = 0.4267
 *
 *   色度分量：
 *     chroma_R = 0.8 - 0.4267 = +0.3733  （偏红，正偏差）
 *     chroma_G = 0.3 - 0.4267 = -0.1267  （绿略低于亮度基准）
 *     chroma_B = 0.1 - 0.4267 = -0.3267  （蓝明显低于亮度基准）
 *
 *   不同 saturation 下的输出：
 *
 *     sat=0   → (0.43, 0.43, 0.43)  灰色（约 43% 亮度）
 *     sat=0.5 → (0.61, 0.36, 0.26)  淡橙色（向灰色靠近了一半）
 *     sat=1.0 → (0.80, 0.30, 0.10)  原始橙色
 *     sat=1.5 → (0.99, 0.24, 0.00)  浓郁橙色（B 被 clamp 到 0）
 *     sat=2.0 → (1.00, 0.17, 0.00)  过饱和（R 和 B 都被 clamp）
 *
 *   可以看到 sat=1.5 时 B 已为负被 clamp 掉，sat=2.0 时 R 也触顶。
 *   这就是本方法的局限性 —— 它不保护色相，过度调整可能导致偏色。
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 七、公式汇总
 * ───────────────────────────────────────────────────────────────────────────
 *
 *   1. 计算亮度（luma）：
 *      luma = 0.299×R + 0.587×G + 0.114×B
 *
 *   2. 调整饱和度（色度分量缩放）：
 *      R_new = clamp01(luma + saturation × (R - luma))
 *      G_new = clamp01(luma + saturation × (G - luma))
 *      B_new = clamp01(luma + saturation × (B - luma))
 *
 *   当 saturation=0：R_new = G_new = B_new = luma（完全灰度图）
 *   当 saturation=1：不变
 *   当 saturation=2：饱和度翻倍（颜色更鲜艳）
 *
 * ── 3.4 Gamma 校正 ──
 *
 * 【为什么需要 Gamma 校正？】
 *   1. 人眼对暗部的亮度变化比亮部更敏感（非线性的视觉响应）。
 *   2. CRT/LCD 显示器的电光转换也是非线性的。
 *   3. 如果直接用线性数据存储，暗部细节会丢失（因为暗部用太少的码值）。
 *
 * 【Gamma 编码公式】
 *   output = input^(1/gamma)
 *
 *   通常 gamma = 2.2（sRGB 标准），所以：
 *   output = input^(1/2.2) ≈ input^0.45
 *
 *   这条曲线会把暗部"拉伸"（用更多码值表示），亮部"压缩"。
 *   显示器显示时自动做相反的 gamma 解码（^2.2），
 *   二者的乘积 = 1.0，保证总体响应是线性的。
 *
 *   整体流程：
 *   线性光 → [^0.45 Gamma编码] → 存储/传输 → [^2.2 显示器解码] → 线性光到达人眼
 *
 * 这个函数输出两种 RGB：
 *   linear_rgb  — 去马赛克后的线性 RGB（没有 Gamma 校正，暗部偏暗）
 *   display_rgb — 经过 CCM + 饱和度 + Gamma 的完整 RGB（适合显示和观看）
 */
static void demosaic_and_finish(const float *plane,
                                uint8_t *linear_rgb,
                                uint8_t *display_rgb,
                                const Config *cfg)
{
    /*
     * 预设的颜色校正矩阵（base_ccm）
     *
     * 这是一个典型日用场景（D65 光源）的 CCM 矩阵：
     *
     *   [ 1.20  -0.12  -0.08 ]    ← 增强红色，减去少量绿蓝色串扰
     *   [-0.05   1.10  -0.05 ]    ← 增强绿色，减去少量红蓝串扰
     *   [-0.03  -0.22   1.25 ]    ← 增强蓝色（校正较强），减去较多绿色串扰
     *
     * 可以看到对角线 > 1（增强自身），非对角线为负（减去串扰）。
     * 蓝色通道的非对角线最负，因为传感器上蓝绿串扰通常最严重。
     */
    static const float base_ccm[3][3] = {
        { 1.20f, -0.12f, -0.08f },
        { -0.05f, 1.10f, -0.05f },
        { -0.03f, -0.22f, 1.25f },
    };
    float ccm[3][3];  // 最终使用的 CCM 矩阵（根据 ccm_strength 插值得到）

    int x;
    int y;
    float inv_gamma = 1.0f / cfg->gamma;  // gamma 编码的指数：1/2.2 ≈ 0.455
    float ccm_strength = cfg->ccm_strength;
    float saturation = cfg->saturation;
    int row;
    int col;

    // ---- 将 ccm_strength 和 saturation clamp 到合理范围 ----
    if (ccm_strength < 0.0f)
        ccm_strength = 0.0f;
    if (ccm_strength > 2.0f)
        ccm_strength = 2.0f;
    if (saturation < 0.0f)
        saturation = 0.0f;
    if (saturation > 2.5f)
        saturation = 2.5f;

    /*
     * ---- 构建最终的 CCM 矩阵 ----
     *
     * 在单位矩阵和 base_ccm 之间线性插值：
     *   CCM_final[i][j] = I[i][j] + (base_ccm[i][j] - I[i][j]) × strength
     *
     * 其中 I[i][j] = 1（当 i=j 时）, 0（当 i≠j 时）
     *
     * ccm_strength=0: 对角线全为 1+0=1，其余为 0+0=0 → 就是单位矩阵，不做校正
     * ccm_strength=1: 等于 base_ccm 本身的矩阵
     */
    for (row = 0; row < 3; ++row) {
        for (col = 0; col < 3; ++col) {
            float identity = (row == col) ? 1.0f : 0.0f;  // 单位矩阵元素
            ccm[row][col] = identity + (base_ccm[row][col] - identity) * ccm_strength;
        }
    }

    /*
     * ---- 主循环：逐像素处理 ----
     *
     * 每个像素需要经历：
     *   1. 去马赛克（从 Bayer 单通道恢复 RGB 三通道）
     *   2. 写入 linear_rgb（保存中间结果）
     *   3. CCM 颜色校正
     *   4. 饱和度调整
     *   5. Gamma 编码
     *   6. 写入 display_rgb（保存最终结果）
     */
    for (y = 0; y < cfg->height; ++y) {
        for (x = 0; x < cfg->width; ++x) {
            float r, g, b;    // 去马赛克后的 RGB（线性空间）
            float rr, gg, bb;  // 经过 CCM 和饱和度处理后的 RGB
            // display_rgb 的字节索引（每像素3字节 = R,G,B）
            size_t idx = ((size_t)y * (size_t)cfg->width + (size_t)x) * 3u;

            /*
             * ============================================================
             * 步骤 3.1: 去马赛克 (Demosaicing) — 双线性插值
             * ============================================================
             *
             * 根据当前像素在 Bayer 模式中的位置，分四种情况处理。
             *
             * y&1 和 x&1 的结果：
             *   y&1==0, x&1==0 → R 像素（RGGB 的 R，在偶行偶列）
             *   y&1==1, x&1==1 → B 像素（RGGB 的 B，在奇行奇列）
             *   y&1==0, x&1==1 → Gr 像素（偶行奇列，R 行中的 G）
             *   y&1==1, x&1==0 → Gb 像素（奇行偶列，B 行中的 G）
             */

            if ((y & 1) == 0 && (x & 1) == 0) {
                /*
                 * R 像素位置（偶行偶列）
                 *
                 * 邻域示意（当前像素被标记为 [R]）：
                 *   B(-1,-1)  G(0,-1)  B(+1,-1)
                 *   G(-1,0)   [R](0,0) G(+1,0)
                 *   B(-1,+1)  G(0,+1)  B(+1,+1)
                 *
                 * R = 当前像素值（已知）
                 * G = 上下左右 4 个 G 的平均（因为 R 的正上下左右恰好都是 G）
                 * B = 四个对角 B 的平均
                 */
                r = sample_plane(plane, cfg->width, cfg->height, x, y);

                g = (sample_plane(plane, cfg->width, cfg->height, x - 1, y) +      // 左
                     sample_plane(plane, cfg->width, cfg->height, x + 1, y) +      // 右
                     sample_plane(plane, cfg->width, cfg->height, x, y - 1) +      // 上
                     sample_plane(plane, cfg->width, cfg->height, x, y + 1))       // 下
                    * 0.25f;  // 除以 4

                b = (sample_plane(plane, cfg->width, cfg->height, x - 1, y - 1) +  // 左上
                     sample_plane(plane, cfg->width, cfg->height, x + 1, y - 1) +  // 右上
                     sample_plane(plane, cfg->width, cfg->height, x - 1, y + 1) +  // 左下
                     sample_plane(plane, cfg->width, cfg->height, x + 1, y + 1))   // 右下
                    * 0.25f;  // 除以 4

            } else if ((y & 1) == 1 && (x & 1) == 1) {
                /*
                 * B 像素位置（奇行奇列）—— 与 R 完全对称
                 *
                 * 邻域示意：
                 *   R(-1,-1)  G(0,-1)  R(+1,-1)
                 *   G(-1,0)   [B](0,0) G(+1,0)
                 *   R(-1,+1)  G(0,+1)  R(+1,+1)
                 *
                 * B = 当前像素值（已知）
                 * G = 上下左右 4 个 G 的平均
                 * R = 四个对角 R 的平均
                 */
                b = sample_plane(plane, cfg->width, cfg->height, x, y);

                g = (sample_plane(plane, cfg->width, cfg->height, x - 1, y) +
                     sample_plane(plane, cfg->width, cfg->height, x + 1, y) +
                     sample_plane(plane, cfg->width, cfg->height, x, y - 1) +
                     sample_plane(plane, cfg->width, cfg->height, x, y + 1))
                    * 0.25f;

                r = (sample_plane(plane, cfg->width, cfg->height, x - 1, y - 1) +
                     sample_plane(plane, cfg->width, cfg->height, x + 1, y - 1) +
                     sample_plane(plane, cfg->width, cfg->height, x - 1, y + 1) +
                     sample_plane(plane, cfg->width, cfg->height, x + 1, y + 1))
                    * 0.25f;

            } else if ((y & 1) == 0) {
                /*
                 * Gr 像素位置（偶行奇列，R 行中的 G）
                 *
                 * 邻域示意：
                 *   R(-1,-1)  G(0,-1)  R(+1,-1)
                 *   [G](-1,0) G(0,0)   [G](+1,0)    ← 等等，这里不太对...
                 *   R(-1,+1)  G(0,+1)  R(+1,+1)
                 *
                 * 实际上 Gr 的相邻关系是：
                 *   左(-1,0)=R, 右(+1,0)=R  → R = 左右 R 的平均
                 *   上(0,-1)=B, 下(0,+1)=B  → B = 上下 B 的平均
                 */
                g = sample_plane(plane, cfg->width, cfg->height, x, y);

                r = (sample_plane(plane, cfg->width, cfg->height, x - 1, y) +   // 左（R）
                     sample_plane(plane, cfg->width, cfg->height, x + 1, y))    // 右（R）
                    * 0.5f;  // 除以 2

                b = (sample_plane(plane, cfg->width, cfg->height, x, y - 1) +   // 上（B）
                     sample_plane(plane, cfg->width, cfg->height, x, y + 1))    // 下（B）
                    * 0.5f;

            } else {
                /*
                 * Gb 像素位置（奇行偶列，B 行中的 G）
                 *
                 * 与 Gr 对称：
                 *   上(0,-1)=R, 下(0,+1)=R  → R = 上下 R 的平均
                 *   左(-1,0)=B, 右(+1,0)=B  → B = 左右 B 的平均
                 */
                g = sample_plane(plane, cfg->width, cfg->height, x, y);

                r = (sample_plane(plane, cfg->width, cfg->height, x, y - 1) +   // 上（R）
                     sample_plane(plane, cfg->width, cfg->height, x, y + 1))    // 下（R）
                    * 0.5f;

                b = (sample_plane(plane, cfg->width, cfg->height, x - 1, y) +   // 左（B）
                     sample_plane(plane, cfg->width, cfg->height, x + 1, y))    // 右（B）
                    * 0.5f;
            }

            /*
             * ---- 保存去马赛克后的线性 RGB（阶段3.1 中间结果） ----
             *
             * 这是未经 Gamma 校正的"原始"RGB，
             * 看着会偏暗，但保留了物理上的线性关系，方便后续计算。
             */
            linear_rgb[idx + 0] = clamp_u8(clamp01(r) * 255.0f);
            linear_rgb[idx + 1] = clamp_u8(clamp01(g) * 255.0f);
            linear_rgb[idx + 2] = clamp_u8(clamp01(b) * 255.0f);

            /*
             * ============================================================
             * 步骤 3.2: 颜色校正矩阵 (CCM)
             * ============================================================
             *
             * 3×3 矩阵乘法，将传感器色彩空间映射到标准色彩空间。
             *
             * rr = ccm[0][0]*r + ccm[0][1]*g + ccm[0][2]*b
             * gg = ccm[1][0]*r + ccm[1][1]*g + ccm[1][2]*b
             * bb = ccm[2][0]*r + ccm[2][1]*g + ccm[2][2]*b
             */
            rr = clamp01(ccm[0][0] * r + ccm[0][1] * g + ccm[0][2] * b);
            gg = clamp01(ccm[1][0] * r + ccm[1][1] * g + ccm[1][2] * b);
            bb = clamp01(ccm[2][0] * r + ccm[2][1] * g + ccm[2][2] * b);

            /*
             * ============================================================
             * 步骤 3.3: 饱和度调整
             * ============================================================
             *
             * 先算亮度（luma），然后在亮度不变的前提下调整饱和度：
             *
             *   luma = 0.299×R + 0.587×G + 0.114×B
             *
             * 这个公式反映了人眼对不同波长的敏感度：
             *   绿色 58.7% > 红色 29.9% > 蓝色 11.4%
             *
             * 饱和度调整公式：
             *   out = luma + saturation × (in - luma)
             *
             * 理解：saturation=0 时 out=luma（完全去色），
             *       saturation=1 时 out=in（原始饱和度），
             *       saturation>1 时颜色被"拉离"灰度（更鲜艳）。
             */
            {
                float luma = 0.299f * rr + 0.587f * gg + 0.114f * bb;
                rr = clamp01(luma + saturation * (rr - luma));
                gg = clamp01(luma + saturation * (gg - luma));
                bb = clamp01(luma + saturation * (bb - luma));
            }

            /*
             * ============================================================
             * 步骤 3.4: Gamma 编码
             * ============================================================
             *
             * 对每个通道做幂运算：output = input^(1/gamma)
             *
             * 如果 gamma=2.2，则 output = input^(1/2.2) ≈ input^0.455
             *
             * 效果：
             *   暗部（如 input=0.2 → output≈0.48）：被大幅提亮
             *   亮部（如 input=0.8 → output≈0.90）：变化较小
             *
             * 这确保了暗部不会被压缩到仅有的几个码值上，
             * 从而保留暗部细节。
             */
            rr = powf(rr, inv_gamma);
            gg = powf(gg, inv_gamma);
            bb = powf(bb, inv_gamma);

            /*
             * ---- 保存最终的 display_rgb ----
             *
             * 这是经过完整 ISP 处理的、适合在显示器上直接观看的 RGB 数据。
             */
            display_rgb[idx + 0] = clamp_u8(clamp01(rr) * 255.0f);
            display_rgb[idx + 1] = clamp_u8(clamp01(gg) * 255.0f);
            display_rgb[idx + 2] = clamp_u8(clamp01(bb) * 255.0f);
        }
    }
}

/* ====================================================================
 * ╔═══════════════════════════════════════════════════════════════════╗
 * ║    参考附录：高级去马赛克算法的示例实现（仅供学习，切勿用于生产）    ║
 * ╚═══════════════════════════════════════════════════════════════════╝
 *
 * 下面的三个函数 —— demosaic_bilinear_reference、demosaic_mhc_reference、
 * demosaic_vng_reference —— 是三种去马赛克算法的独立、自包含的参考实现。
 *
 * 设计目标：
 *   - 每个函数都可以脱离 Pipeline 独立运行（输入 Bayer 浮点平面，输出 RGB24）
 *   - 代码刻意展开、加了大量中间变量和注释，以可读性为最高优先级
 *   - 不做任何性能优化（不 SIMD、不分块、不预计算），故意"笨拙"以保持清晰
 *
 * ⚠️  警告：这些函数仅用于帮助理解算法原理。实际工程中请使用 libraw、dcraw
 *     或 Halide/OpenCV 中经过充分测试和优化的实现。以下代码存在以下已知问题：
 *       1. 完全没有性能优化，处理一张 12MP 图像可能需要数十秒
 *       2. 边界处理采用了最简单的 clamp-to-edge，会在图像边界产生伪影
 *       3. VNG 的梯度阈值是硬编码的魔数，未针对任何具体传感器标定
 *       4. 没有任何针对饱和像素、坏点、噪声的防护逻辑
 *       5. 没有处理 Gr/Gb 不对称性（真实传感器的 R 行 G 和 B 行 G 灵敏度不同）
 *
 * 每个函数的参数：
 *   plane  : 指向 Bayer 浮点平面的指针（大小为 width × height，值范围 [0, 1]）
 *   width  : 图像宽度
 *   height : 图像高度
 *   rgb_out: 输出的 RGB24 缓冲区（大小为 width × height × 3 字节，调用者分配）
 *
 * 所有函数都假设 RGGB Bayer Pattern（最常见的排列方式）。
 * ==================================================================== */

/* 安全地从 Bayer 浮点平面取值（带边界 clamp-to-edge） */
static float ref_sample_plane(const float *plane, int width, int height, int x, int y)
{
    if (x < 0) x = 0; else if (x >= width) x = width - 1;
    if (y < 0) y = 0; else if (y >= height) y = height - 1;
    return plane[(size_t)y * (size_t)width + (size_t)x];
}

/* ====================================================================
 * 参考实现 1: 双线性插值 (Bilinear Interpolation) — 独立函数版
 * ====================================================================
 *
 * 这是 Pipeline 主流程中 demosaic_and_finish() 的去马赛克部分的独立提取版。
 * 将它与 MHC、VNG 放在一起对比阅读，可以最直观地理解三种算法的差异。
 */
static void demosaic_bilinear_reference(const float *plane,
                                        int width, int height,
                                        uint8_t *rgb_out)
{
    int x, y;

    for (y = 0; y < height; ++y) {
        for (x = 0; x < width; ++x) {
            float r, g, b;
            size_t idx = ((size_t)y * (size_t)width + (size_t)x) * 3u;

            if ((y & 1) == 0 && (x & 1) == 0) {
                /* R 像素位置（偶行偶列） */
                r = ref_sample_plane(plane, width, height, x, y);

                g = (ref_sample_plane(plane, width, height, x - 1, y) +
                     ref_sample_plane(plane, width, height, x + 1, y) +
                     ref_sample_plane(plane, width, height, x, y - 1) +
                     ref_sample_plane(plane, width, height, x, y + 1)) * 0.25f;

                b = (ref_sample_plane(plane, width, height, x - 1, y - 1) +
                     ref_sample_plane(plane, width, height, x + 1, y - 1) +
                     ref_sample_plane(plane, width, height, x - 1, y + 1) +
                     ref_sample_plane(plane, width, height, x + 1, y + 1)) * 0.25f;

            } else if ((y & 1) == 1 && (x & 1) == 1) {
                /* B 像素位置（奇行奇列） */
                b = ref_sample_plane(plane, width, height, x, y);

                g = (ref_sample_plane(plane, width, height, x - 1, y) +
                     ref_sample_plane(plane, width, height, x + 1, y) +
                     ref_sample_plane(plane, width, height, x, y - 1) +
                     ref_sample_plane(plane, width, height, x, y + 1)) * 0.25f;

                r = (ref_sample_plane(plane, width, height, x - 1, y - 1) +
                     ref_sample_plane(plane, width, height, x + 1, y - 1) +
                     ref_sample_plane(plane, width, height, x - 1, y + 1) +
                     ref_sample_plane(plane, width, height, x + 1, y + 1)) * 0.25f;

            } else if ((y & 1) == 0) {
                /* Gr 像素位置（偶行奇列，R 行中的 G） */
                g = ref_sample_plane(plane, width, height, x, y);

                r = (ref_sample_plane(plane, width, height, x - 1, y) +
                     ref_sample_plane(plane, width, height, x + 1, y)) * 0.5f;

                b = (ref_sample_plane(plane, width, height, x, y - 1) +
                     ref_sample_plane(plane, width, height, x, y + 1)) * 0.5f;

            } else {
                /* Gb 像素位置（奇行偶列，B 行中的 G） */
                g = ref_sample_plane(plane, width, height, x, y);

                r = (ref_sample_plane(plane, width, height, x, y - 1) +
                     ref_sample_plane(plane, width, height, x, y + 1)) * 0.5f;

                b = (ref_sample_plane(plane, width, height, x - 1, y) +
                     ref_sample_plane(plane, width, height, x + 1, y)) * 0.5f;
            }

            rgb_out[idx + 0] = clamp_u8(clamp01(r) * 255.0f);
            rgb_out[idx + 1] = clamp_u8(clamp01(g) * 255.0f);
            rgb_out[idx + 2] = clamp_u8(clamp01(b) * 255.0f);
        }
    }
}

/* ====================================================================
 * 参考实现 2: Malvar-He-Cutler (MHC) 算法
 * ====================================================================
 *
 * 这是对 Microsoft Research 2004 年论文 "High-Quality Linear Interpolation
 * for Demosaicing of Bayer-Patterned Color Images" 的代码翻译。
 *
 * 【核心思想】在双线性插值的基础上加入"梯度校正项"：
 *
 *   最终值 = 邻域加权平均 + alpha × (中心像素 - 邻域对中心像素的估计)
 *
 * 公式中的 W(dx, dy) = ref_sample_plane(plane, width, height, x+dx, y+dy)，
 * 即中心像素 (x,y) 的 5×5 邻域中偏移 (dx,dy) 处的值。
 */
static void demosaic_mhc_reference(const float *plane,
                                   int width, int height,
                                   uint8_t *rgb_out)
{
    int x, y;

    for (y = 0; y < height; ++y) {
        for (x = 0; x < width; ++x) {
            float r, g, b;
            size_t idx = ((size_t)y * (size_t)width + (size_t)x) * 3u;

#define W(dx, dy) ref_sample_plane(plane, width, height, x + (dx), y + (dy))

            if ((y & 1) == 0 && (x & 1) == 0) {
                /* ========================================================
                 * R 像素位置（偶行偶列）—— 已知 R，缺 G 和 B
                 *
                 * 5×5 邻域中 G 像素位于上下左右的 4 个正交邻接位和
                 * 更远一格的 4 个正交位。B 像素位于 4 个对角位。
                 * ======================================================== */

                r = W(0, 0);

                /* ── G 的 MHC 插值 ──
                 *
                 * 第一步：对 G 像素做 5×5 加权和
                 *   正交 G（上下左右）权重 = +4
                 *   远正交 G（隔一个像素）权重 = -1
                 *   归一化因子 = 1/16
                 */
                float g_linear =
                    (W(-1,  0) * 4.0f + W( 1,  0) * 4.0f +
                     W( 0, -1) * 4.0f + W( 0,  1) * 4.0f +
                     W(-2,  0) * -1.0f + W( 2,  0) * -1.0f +
                     W( 0, -2) * -1.0f + W( 0,  2) * -1.0f) / 16.0f;

                /*
                 * 第二步：梯度校正
                 * 用水平和竖直方向的梯度动态决定校正强度 alpha。
                 * alpha 大 → 平坦区域 → 强校正；alpha 小 → 边缘区域 → 弱校正（避免跨边缘）。
                 */
                float grad_H = fabsf(W(-2, 0) + W(2, 0) - 2.0f * r);
                float grad_V = fabsf(W(0, -2) + W(0, 2) - 2.0f * r);
                float denom_H = fabsf(W(-2, 0) - W(2, 0)) + 0.0001f;
                float denom_V = fabsf(W(0, -2) - W(0, 2)) + 0.0001f;
                float alpha_H = grad_H / denom_H;
                float alpha_V = grad_V / denom_V;
                float alpha_max = (alpha_H > alpha_V) ? alpha_H : alpha_V;
                float alpha = 0.5f * (1.0f - alpha_max);
                if (alpha < 0.0f) alpha = 0.0f;
                if (alpha > 0.5f) alpha = 0.5f;

                float r_laplacian = (4.0f * r - W(-2, 0) - W(2, 0) - W(0, -2) - W(0, 2));
                g = g_linear + alpha * r_laplacian / 4.0f;

                /* ── B 的 MHC 插值 ──
                 *
                 * 4 个对角 B 做简单平均，然后用 G 的局部偏差做校正。
                 * 校正系数 0.375 来自论文中 B at R 的经验值。
                 */
                float b_linear =
                    (W(-1, -1) + W( 1, -1) + W(-1,  1) + W( 1,  1)) * 0.25f;

                float g_neighbors_for_b =
                    (W(-1, 0) + W(1, 0) + W(0, -1) + W(0, 1)) * 0.25f;
                float g_deviation = g - g_neighbors_for_b;

                b = clamp01(b_linear + 0.375f * g_deviation);

            } else if ((y & 1) == 1 && (x & 1) == 1) {
                /* ========================================================
                 * B 像素位置（奇行奇列）—— 与 R 位置完全对称
                 * 将 R 位置公式中的 R 和 B 互换即可
                 * ======================================================== */

                b = W(0, 0);

                /* G 插值（与 R 位置相同） */
                float g_linear =
                    (W(-1,  0) * 4.0f + W( 1,  0) * 4.0f +
                     W( 0, -1) * 4.0f + W( 0,  1) * 4.0f +
                     W(-2,  0) * -1.0f + W( 2,  0) * -1.0f +
                     W( 0, -2) * -1.0f + W( 0,  2) * -1.0f) / 16.0f;

                float grad_H = fabsf(W(-2, 0) + W(2, 0) - 2.0f * b);
                float grad_V = fabsf(W(0, -2) + W(0, 2) - 2.0f * b);
                float denom_H = fabsf(W(-2, 0) - W(2, 0)) + 0.0001f;
                float denom_V = fabsf(W(0, -2) - W(0, 2)) + 0.0001f;
                float alpha_H = grad_H / denom_H;
                float alpha_V = grad_V / denom_V;
                float alpha_max = (alpha_H > alpha_V) ? alpha_H : alpha_V;
                float alpha = 0.5f * (1.0f - alpha_max);
                if (alpha < 0.0f) alpha = 0.0f;
                if (alpha > 0.5f) alpha = 0.5f;

                float b_laplacian = (4.0f * b - W(-2, 0) - W(2, 0) - W(0, -2) - W(0, 2));
                g = g_linear + alpha * b_laplacian / 4.0f;

                /* R 插值（对角方向） */
                float r_linear =
                    (W(-1, -1) + W( 1, -1) + W(-1,  1) + W( 1,  1)) * 0.25f;

                float g_neighbors_for_r =
                    (W(-1, 0) + W(1, 0) + W(0, -1) + W(0, 1)) * 0.25f;
                float g_deviation = g - g_neighbors_for_r;

                r = clamp01(r_linear + 0.375f * g_deviation);

            } else if ((y & 1) == 0) {
                /* ========================================================
                 * Gr 像素位置（偶行奇列，R 行中的 G）
                 * 已知: G(0,0)    左右 (-1,0) 和 (+1,0) 是 R
                 *               上下 (0,-1) 和 (0,+1) 是 B
                 * ======================================================== */

                g = W(0, 0);

                /* ── R 的插值 ──
                 * 核心来自左右已知 R（权重 5），辅助来自上下估算 R（权重 4），
                 * 远处 R 起锐化校正（权重 -1），归一化 1/16。
                 */
                {
                    float r_left  = W(-1, 0);
                    float r_right = W( 1, 0);
                    float r_top_est    = (W(-1, -1) + W( 1, -1)) * 0.5f;
                    float r_bottom_est = (W(-1,  1) + W( 1,  1)) * 0.5f;
                    float r_far_left  = W(-3, 0);
                    float r_far_right = W( 3, 0);

                    float r_linear =
                        (r_left  * 5.0f + r_right * 5.0f +
                         r_top_est * 4.0f + r_bottom_est * 4.0f +
                         r_far_left * -1.0f + r_far_right * -1.0f) / 16.0f;

                    float g_neighbors =
                        (W(-1, 0) + W(1, 0) + W(0, -1) + W(0, 1)) * 0.25f;
                    float g_deviation = g - g_neighbors;

                    r = clamp01(r_linear + 0.5f * g_deviation);
                }

                /* ── B 的插值（与 R 对称）── */
                {
                    float b_top    = W( 0, -1);
                    float b_bottom = W( 0,  1);
                    float b_left_est  = (W(-1, -1) + W(-1,  1)) * 0.5f;
                    float b_right_est = (W( 1, -1) + W( 1,  1)) * 0.5f;
                    float b_far_top    = W( 0, -3);
                    float b_far_bottom = W( 0,  3);

                    float b_linear =
                        (b_top  * 5.0f + b_bottom * 5.0f +
                         b_left_est * 4.0f + b_right_est * 4.0f +
                         b_far_top * -1.0f + b_far_bottom * -1.0f) / 16.0f;

                    float g_neighbors =
                        (W(-1, 0) + W(1, 0) + W(0, -1) + W(0, 1)) * 0.25f;
                    float g_deviation = g - g_neighbors;

                    b = clamp01(b_linear + 0.5f * g_deviation);
                }

            } else {
                /* ========================================================
                 * Gb 像素位置（奇行偶列，B 行中的 G）
                 * 与 Gr 对称：上下是 R    左右是 B
                 * ======================================================== */

                g = W(0, 0);

                /* ── R 的插值（与 Gr 的 B 对称）── */
                {
                    float r_top    = W( 0, -1);
                    float r_bottom = W( 0,  1);
                    float r_left_est  = (W(-1, -1) + W(-1,  1)) * 0.5f;
                    float r_right_est = (W( 1, -1) + W( 1,  1)) * 0.5f;
                    float r_far_top    = W( 0, -3);
                    float r_far_bottom = W( 0,  3);

                    float r_linear =
                        (r_top  * 5.0f + r_bottom * 5.0f +
                         r_left_est * 4.0f + r_right_est * 4.0f +
                         r_far_top * -1.0f + r_far_bottom * -1.0f) / 16.0f;

                    float g_neighbors =
                        (W(-1, 0) + W(1, 0) + W(0, -1) + W(0, 1)) * 0.25f;
                    float g_deviation = g - g_neighbors;

                    r = clamp01(r_linear + 0.5f * g_deviation);
                }

                /* ── B 的插值（与 Gr 的 R 对称）── */
                {
                    float b_left  = W(-1, 0);
                    float b_right = W( 1, 0);
                    float b_top_est    = (W(-1, -1) + W( 1, -1)) * 0.5f;
                    float b_bottom_est = (W(-1,  1) + W( 1,  1)) * 0.5f;
                    float b_far_left  = W(-3, 0);
                    float b_far_right = W( 3, 0);

                    float b_linear =
                        (b_left  * 5.0f + b_right * 5.0f +
                         b_top_est * 4.0f + b_bottom_est * 4.0f +
                         b_far_left * -1.0f + b_far_right * -1.0f) / 16.0f;

                    float g_neighbors =
                        (W(-1, 0) + W(1, 0) + W(0, -1) + W(0, 1)) * 0.25f;
                    float g_deviation = g - g_neighbors;

                    b = clamp01(b_linear + 0.5f * g_deviation);
                }
            }

#undef W

            rgb_out[idx + 0] = clamp_u8(clamp01(r) * 255.0f);
            rgb_out[idx + 1] = clamp_u8(clamp01(g) * 255.0f);
            rgb_out[idx + 2] = clamp_u8(clamp01(b) * 255.0f);
        }
    }
}

/* ====================================================================
 * 参考实现 3: VNG (Variable Number of Gradients) 算法
 * ====================================================================
 *
 * 这是对 VNG 论文思想的简化实现。核心流程：
 *   1. 对 5×5 邻域计算 8 个方向的梯度
 *   2. 排除梯度太大的方向（梯度 > 最小梯度 × 2）
 *   3. 用剩余方向的像素做加权平均（权重 = 1/(梯度 + ε)）
 *
 * 为了保持代码可读性，这里对论文做了一些简化：
 *   - 梯度阈值使用固定倍数（2× 最小梯度）而非自适应策略
 *   - Gr 和 Gb 统一处理为一个 G 类
 *
 * 【VNG 方向编号】
 *         5(NW)  0(N)  4(NE)
 *           \    |    /
 *     3(W) —  [中心]  — 2(E)
 *           /    |    \
 *         7(SW)  1(S)  6(SE)
 */
static void demosaic_vng_reference(const float *plane,
                                   int width, int height,
                                   uint8_t *rgb_out)
{
    int x, y;

    for (y = 0; y < height; ++y) {
        for (x = 0; x < width; ++x) {
            float r, g, b;
            size_t idx = ((size_t)y * (size_t)width + (size_t)x) * 3u;

            /* 构建 5×5 窗口，p[2][2] 是中心像素 */
            float p[5][5];
            int dy, dx;
            for (dy = -2; dy <= 2; ++dy)
                for (dx = -2; dx <= 2; ++dx)
                    p[dy+2][dx+2] = ref_sample_plane(plane, width, height, x + dx, y + dy);

            if ((y & 1) == 0 && (x & 1) == 0) {
                /* ========================================================
                 * R 像素位置（偶行偶列）
                 * ======================================================== */

                r = p[2][2];

                /* ── G 的 8 方向梯度投票 ── */
                {
                    float grads[8], g_vals[8];

                    /* N (正北) */
                    grads[0] = (fabsf(p[1][1] - p[1][2]) + fabsf(p[3][1] - p[3][2]) +
                                fabsf(p[1][2] - p[1][3]) + fabsf(p[1][1] - p[3][1])) * 0.25f;
                    g_vals[0] = p[2][1];

                    /* S (正南) */
                    grads[1] = (fabsf(p[1][3] - p[1][2]) + fabsf(p[3][3] - p[3][2]) +
                                fabsf(p[1][2] - p[1][1]) + fabsf(p[1][3] - p[3][3])) * 0.25f;
                    g_vals[1] = p[2][3];

                    /* E (正东) */
                    grads[2] = (fabsf(p[1][1] - p[2][1]) + fabsf(p[1][3] - p[2][3]) +
                                fabsf(p[2][1] - p[3][1]) + fabsf(p[2][3] - p[3][3])) * 0.25f;
                    g_vals[2] = p[3][2];

                    /* W (正西) */
                    grads[3] = (fabsf(p[1][1] - p[0][1]) + fabsf(p[1][3] - p[0][3]) +
                                fabsf(p[0][1] - p[0][2]) + fabsf(p[0][3] - p[2][3])) * 0.25f;
                    g_vals[3] = p[1][2];

                    /* NE (东北对角线) —— 上 G 和右 G 的平均 */
                    grads[4] = (fabsf(p[2][1] - p[3][2]) + fabsf(p[1][0] - p[2][1]) +
                                fabsf(p[3][2] - p[4][3])) * 0.333f;
                    g_vals[4] = (p[2][1] + p[3][2]) * 0.5f;

                    /* NW (西北对角线) */
                    grads[5] = (fabsf(p[2][1] - p[1][2]) + fabsf(p[3][0] - p[2][1]) +
                                fabsf(p[1][2] - p[0][3])) * 0.333f;
                    g_vals[5] = (p[2][1] + p[1][2]) * 0.5f;

                    /* SE (东南对角线) */
                    grads[6] = (fabsf(p[2][3] - p[3][2]) + fabsf(p[3][2] - p[4][1]) +
                                fabsf(p[1][4] - p[2][3])) * 0.333f;
                    g_vals[6] = (p[2][3] + p[3][2]) * 0.5f;

                    /* SW (西南对角线) */
                    grads[7] = (fabsf(p[2][3] - p[1][2]) + fabsf(p[1][2] - p[0][1]) +
                                fabsf(p[3][4] - p[2][3])) * 0.333f;
                    g_vals[7] = (p[2][3] + p[1][2]) * 0.5f;

                    /* 梯度筛选 + 加权平均 */
                    float min_grad = grads[0];
                    int i;
                    for (i = 1; i < 8; ++i)
                        if (grads[i] < min_grad) min_grad = grads[i];

                    float threshold = min_grad * 2.0f + 0.001f;
                    float weight_sum = 0.0f, g_sum = 0.0f;

                    for (i = 0; i < 8; ++i) {
                        if (grads[i] <= threshold) {
                            float w = 1.0f / (grads[i] + 0.0001f);
                            g_sum += g_vals[i] * w;
                            weight_sum += w;
                        }
                    }

                    g = (weight_sum > 0.0f) ? (g_sum / weight_sum) :
                        (p[1][2] + p[3][2] + p[2][1] + p[2][3]) * 0.25f;
                }

                /* ── B 的梯度投票（4 个对角方向）── */
                {
                    float b_vals[4], b_grads[4];
                    float b_weight_sum = 0.0f, b_sum = 0.0f;

                    b_vals[0] = p[3][1];   /* NE: (+1, -1) */
                    b_grads[0] = fabsf(p[2][1] - p[3][2]) + fabsf(p[3][0] - p[2][1]);

                    b_vals[1] = p[1][1];   /* NW: (-1, -1) */
                    b_grads[1] = fabsf(p[2][1] - p[1][2]) + fabsf(p[1][0] - p[2][1]);

                    b_vals[2] = p[3][3];   /* SE: (+1, +1) */
                    b_grads[2] = fabsf(p[2][3] - p[3][2]) + fabsf(p[3][4] - p[2][3]);

                    b_vals[3] = p[1][3];   /* SW: (-1, +1) */
                    b_grads[3] = fabsf(p[2][3] - p[1][2]) + fabsf(p[1][4] - p[2][3]);

                    float min_bgrad = b_grads[0];
                    int i;
                    for (i = 1; i < 4; ++i)
                        if (b_grads[i] < min_bgrad) min_bgrad = b_grads[i];

                    float b_threshold = min_bgrad * 2.0f + 0.001f;

                    for (i = 0; i < 4; ++i) {
                        if (b_grads[i] <= b_threshold) {
                            float w = 1.0f / (b_grads[i] + 0.0001f);
                            b_sum += b_vals[i] * w;
                            b_weight_sum += w;
                        }
                    }
                    b = clamp01((b_weight_sum > 0.0f) ? (b_sum / b_weight_sum) :
                                (p[1][1] + p[3][1] + p[1][3] + p[3][3]) * 0.25f);
                }

            } else if ((y & 1) == 1 && (x & 1) == 1) {
                /* ========================================================
                 * B 像素位置（奇行奇列）—— 与 R 位置对称
                 * ======================================================== */

                b = p[2][2];

                /* ── G 的 8 方向梯度投票（与 R 位置相同）── */
                {
                    float grads[8], g_vals[8];

                    grads[0] = (fabsf(p[1][1] - p[1][2]) + fabsf(p[3][1] - p[3][2]) +
                                fabsf(p[1][2] - p[1][3]) + fabsf(p[1][1] - p[3][1])) * 0.25f;
                    g_vals[0] = p[2][1];
                    grads[1] = (fabsf(p[1][3] - p[1][2]) + fabsf(p[3][3] - p[3][2]) +
                                fabsf(p[1][2] - p[1][1]) + fabsf(p[1][3] - p[3][3])) * 0.25f;
                    g_vals[1] = p[2][3];
                    grads[2] = (fabsf(p[1][1] - p[2][1]) + fabsf(p[1][3] - p[2][3]) +
                                fabsf(p[2][1] - p[3][1]) + fabsf(p[2][3] - p[3][3])) * 0.25f;
                    g_vals[2] = p[3][2];
                    grads[3] = (fabsf(p[1][1] - p[0][1]) + fabsf(p[1][3] - p[0][3]) +
                                fabsf(p[0][1] - p[0][2]) + fabsf(p[0][3] - p[2][3])) * 0.25f;
                    g_vals[3] = p[1][2];
                    grads[4] = (fabsf(p[2][1] - p[3][2]) + fabsf(p[1][0] - p[2][1]) +
                                fabsf(p[3][2] - p[4][3])) * 0.333f;
                    g_vals[4] = (p[2][1] + p[3][2]) * 0.5f;
                    grads[5] = (fabsf(p[2][1] - p[1][2]) + fabsf(p[3][0] - p[2][1]) +
                                fabsf(p[1][2] - p[0][3])) * 0.333f;
                    g_vals[5] = (p[2][1] + p[1][2]) * 0.5f;
                    grads[6] = (fabsf(p[2][3] - p[3][2]) + fabsf(p[3][2] - p[4][1]) +
                                fabsf(p[1][4] - p[2][3])) * 0.333f;
                    g_vals[6] = (p[2][3] + p[3][2]) * 0.5f;
                    grads[7] = (fabsf(p[2][3] - p[1][2]) + fabsf(p[1][2] - p[0][1]) +
                                fabsf(p[3][4] - p[2][3])) * 0.333f;
                    g_vals[7] = (p[2][3] + p[1][2]) * 0.5f;

                    float min_grad = grads[0];
                    int i;
                    for (i = 1; i < 8; ++i)
                        if (grads[i] < min_grad) min_grad = grads[i];

                    float threshold = min_grad * 2.0f + 0.001f;
                    float weight_sum = 0.0f, g_sum = 0.0f;

                    for (i = 0; i < 8; ++i) {
                        if (grads[i] <= threshold) {
                            float w = 1.0f / (grads[i] + 0.0001f);
                            g_sum += g_vals[i] * w;
                            weight_sum += w;
                        }
                    }
                    g = (weight_sum > 0.0f) ? (g_sum / weight_sum) :
                        (p[1][2] + p[3][2] + p[2][1] + p[2][3]) * 0.25f;
                }

                /* ── R 的梯度投票（4 个对角方向）── */
                {
                    float r_vals[4], r_grads[4];
                    float r_weight_sum = 0.0f, r_sum = 0.0f;

                    r_vals[0] = p[3][1];   r_grads[0] = fabsf(p[2][1] - p[3][2]) + fabsf(p[3][0] - p[2][1]);
                    r_vals[1] = p[1][1];   r_grads[1] = fabsf(p[2][1] - p[1][2]) + fabsf(p[1][0] - p[2][1]);
                    r_vals[2] = p[3][3];   r_grads[2] = fabsf(p[2][3] - p[3][2]) + fabsf(p[3][4] - p[2][3]);
                    r_vals[3] = p[1][3];   r_grads[3] = fabsf(p[2][3] - p[1][2]) + fabsf(p[1][4] - p[2][3]);

                    float min_rgrad = r_grads[0];
                    int i;
                    for (i = 1; i < 4; ++i)
                        if (r_grads[i] < min_rgrad) min_rgrad = r_grads[i];

                    float r_threshold = min_rgrad * 2.0f + 0.001f;

                    for (i = 0; i < 4; ++i) {
                        if (r_grads[i] <= r_threshold) {
                            float w = 1.0f / (r_grads[i] + 0.0001f);
                            r_sum += r_vals[i] * w;
                            r_weight_sum += w;
                        }
                    }
                    r = clamp01((r_weight_sum > 0.0f) ? (r_sum / r_weight_sum) :
                                (p[1][1] + p[3][1] + p[1][3] + p[3][3]) * 0.25f);
                }

            } else if ((y & 1) == 0) {
                /* ========================================================
                 * Gr 像素位置（偶行奇列，R 行中的 G）
                 * 已知: G(0,0)    左右是 R    上下是 B
                 * ======================================================== */

                g = p[2][2];

                /* ── R 的梯度投票 ── */
                {
                    float r_vals[4], r_grads[4];
                    float r_weight_sum = 0.0f, r_sum = 0.0f;

                    r_vals[0] = p[3][2];   /* E: 右 R */
                    r_grads[0] = fabsf(p[2][2] - p[3][2]) + fabsf(p[3][1] - p[3][3]);
                    r_vals[1] = p[1][2];   /* W: 左 R */
                    r_grads[1] = fabsf(p[2][2] - p[1][2]) + fabsf(p[1][1] - p[1][3]);
                    r_vals[2] = (p[2][1] + p[4][1]) * 0.5f;  /* N: 上方估算 R */
                    r_grads[2] = fabsf(p[2][1] - p[2][2]) + fabsf(p[4][1] - p[3][1]);
                    r_vals[3] = (p[2][3] + p[4][3]) * 0.5f;  /* S: 下方估算 R */
                    r_grads[3] = fabsf(p[2][3] - p[2][2]) + fabsf(p[4][3] - p[3][3]);

                    float min_rgrad = r_grads[0];
                    int i;
                    for (i = 1; i < 4; ++i)
                        if (r_grads[i] < min_rgrad) min_rgrad = r_grads[i];

                    float r_threshold = min_rgrad * 2.0f + 0.001f;

                    for (i = 0; i < 4; ++i) {
                        if (r_grads[i] <= r_threshold) {
                            float w = 1.0f / (r_grads[i] + 0.0001f);
                            r_sum += r_vals[i] * w;
                            r_weight_sum += w;
                        }
                    }
                    r = clamp01((r_weight_sum > 0.0f) ? (r_sum / r_weight_sum) :
                                (p[1][2] + p[3][2]) * 0.5f);
                }

                /* ── B 的梯度投票 ── */
                {
                    float b_vals[4], b_grads[4];
                    float b_weight_sum = 0.0f, b_sum = 0.0f;

                    b_vals[0] = p[2][1];   /* N: 上 B */
                    b_grads[0] = fabsf(p[2][2] - p[2][1]) + fabsf(p[1][1] - p[3][1]);
                    b_vals[1] = p[2][3];   /* S: 下 B */
                    b_grads[1] = fabsf(p[2][2] - p[2][3]) + fabsf(p[1][3] - p[3][3]);
                    b_vals[2] = (p[1][1] + p[1][3]) * 0.5f;  /* W: 左侧估算 B */
                    b_grads[2] = fabsf(p[1][2] - p[2][2]) + fabsf(p[1][1] - p[2][1]);
                    b_vals[3] = (p[3][1] + p[3][3]) * 0.5f;  /* E: 右侧估算 B */
                    b_grads[3] = fabsf(p[3][2] - p[2][2]) + fabsf(p[3][1] - p[2][1]);

                    float min_bgrad = b_grads[0];
                    int i;
                    for (i = 1; i < 4; ++i)
                        if (b_grads[i] < min_bgrad) min_bgrad = b_grads[i];

                    float b_threshold = min_bgrad * 2.0f + 0.001f;

                    for (i = 0; i < 4; ++i) {
                        if (b_grads[i] <= b_threshold) {
                            float w = 1.0f / (b_grads[i] + 0.0001f);
                            b_sum += b_vals[i] * w;
                            b_weight_sum += w;
                        }
                    }
                    b = clamp01((b_weight_sum > 0.0f) ? (b_sum / b_weight_sum) :
                                (p[2][1] + p[2][3]) * 0.5f);
                }

            } else {
                /* ========================================================
                 * Gb 像素位置（奇行偶列，B 行中的 G）
                 * 与 Gr 对称：上下是 R    左右是 B
                 * ======================================================== */

                g = p[2][2];

                /* ── R 的梯度投票（与 Gr 的 B 对称）── */
                {
                    float r_vals[4], r_grads[4];
                    float r_weight_sum = 0.0f, r_sum = 0.0f;

                    r_vals[0] = p[2][1];   /* N: 上 R */
                    r_grads[0] = fabsf(p[2][2] - p[2][1]) + fabsf(p[1][1] - p[3][1]);
                    r_vals[1] = p[2][3];   /* S: 下 R */
                    r_grads[1] = fabsf(p[2][2] - p[2][3]) + fabsf(p[1][3] - p[3][3]);
                    r_vals[2] = (p[1][1] + p[1][3]) * 0.5f;
                    r_grads[2] = fabsf(p[1][2] - p[2][2]) + fabsf(p[1][1] - p[2][1]);
                    r_vals[3] = (p[3][1] + p[3][3]) * 0.5f;
                    r_grads[3] = fabsf(p[3][2] - p[2][2]) + fabsf(p[3][1] - p[2][1]);

                    float min_rgrad = r_grads[0];
                    int i;
                    for (i = 1; i < 4; ++i)
                        if (r_grads[i] < min_rgrad) min_rgrad = r_grads[i];

                    float r_threshold = min_rgrad * 2.0f + 0.001f;

                    for (i = 0; i < 4; ++i) {
                        if (r_grads[i] <= r_threshold) {
                            float w = 1.0f / (r_grads[i] + 0.0001f);
                            r_sum += r_vals[i] * w;
                            r_weight_sum += w;
                        }
                    }
                    r = clamp01((r_weight_sum > 0.0f) ? (r_sum / r_weight_sum) :
                                (p[2][1] + p[2][3]) * 0.5f);
                }

                /* ── B 的梯度投票（与 Gr 的 R 对称）── */
                {
                    float b_vals[4], b_grads[4];
                    float b_weight_sum = 0.0f, b_sum = 0.0f;

                    b_vals[0] = p[3][2];   /* E: 右 B */
                    b_grads[0] = fabsf(p[2][2] - p[3][2]) + fabsf(p[3][1] - p[3][3]);
                    b_vals[1] = p[1][2];   /* W: 左 B */
                    b_grads[1] = fabsf(p[2][2] - p[1][2]) + fabsf(p[1][1] - p[1][3]);
                    b_vals[2] = (p[2][1] + p[4][1]) * 0.5f;
                    b_grads[2] = fabsf(p[2][1] - p[2][2]) + fabsf(p[4][1] - p[3][1]);
                    b_vals[3] = (p[2][3] + p[4][3]) * 0.5f;
                    b_grads[3] = fabsf(p[2][3] - p[2][2]) + fabsf(p[4][3] - p[3][3]);

                    float min_bgrad = b_grads[0];
                    int i;
                    for (i = 1; i < 4; ++i)
                        if (b_grads[i] < min_bgrad) min_bgrad = b_grads[i];

                    float b_threshold = min_bgrad * 2.0f + 0.001f;

                    for (i = 0; i < 4; ++i) {
                        if (b_grads[i] <= b_threshold) {
                            float w = 1.0f / (b_grads[i] + 0.0001f);
                            b_sum += b_vals[i] * w;
                            b_weight_sum += w;
                        }
                    }
                    b = clamp01((b_weight_sum > 0.0f) ? (b_sum / b_weight_sum) :
                                (p[1][2] + p[3][2]) * 0.5f);
                }
            }

            rgb_out[idx + 0] = clamp_u8(clamp01(r) * 255.0f);
            rgb_out[idx + 1] = clamp_u8(clamp01(g) * 255.0f);
            rgb_out[idx + 2] = clamp_u8(clamp01(b) * 255.0f);
        }
    }
}

/*
 * ====================================================================
 * 阶段 4: 色彩空间转换 —— RGB 转 YUV 4:2:0
 * ====================================================================
 *
 * ╔═══════════════════════════════════════════════════════════════════════════╗
 * ║  ★ 关键问题：RGB→YUV→RGB 会不会把图像打回 Bayer 时期的"马赛克"状态？      ║
 * ║     "去马赛克好不容易把颜色补全了，YUV 又把颜色丢掉，不就白干了吗？"         ║
 * ╚═══════════════════════════════════════════════════════════════════════════╝
 *
 * 这是一个非常深刻的问题。答案是：
 *
 *   ┌──────────────────────────────────────────────────────────────────┐
 *   │                                                                  │
 *   │  YUV 4:2:0 的色度损失 ≠ Bayer 的颜色缺失                           │
 *   │                                                                  │
 *   │  它们是两个完全不同层面的问题，RGB→YUV→RGB 不会产生 Bayer 式的马赛克。 │
 *   │                                                                  │
 *   └──────────────────────────────────────────────────────────────────┘
 *
 * 让我逐层剖析为什么。
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 第一层：两种"信息丢失"发生在完全不同的阶段
 * ───────────────────────────────────────────────────────────────────────────
 *
 *   Bayer 的颜色缺失（硬件层）              YUV 4:2:0 的色度降采样（编码层）
 *   ──────────────────────────────         ────────────────────────────────
 *
 *   发生时机：传感器采集时                   发生时机：ISP 处理完毕后
 *   丢失原因：物理滤镜遮挡                   丢失原因：人为丢弃（因为人眼不敏感）
 *   丢失了什么：每个感光单元 2/3 的颜色       丢失了什么：色度平面的空间分辨率
 *   能否恢复：不能（物理上就没测到）          能否恢复：大致可以（已知全分辨率色度，
 *                                                     只是被平均化了）
 *
 *   Bayer - 每个位置只知道一种颜色            YUV - 每个位置的 Y 是完整的，
 *          另外两种从未被测量                        UV 是周围 2×2 块的平均
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 第二层：用具体数据对比 Bayer Raw 和 YUV 420 的存储内容
 * ───────────────────────────────────────────────────────────────────────────
 *
 * 假设一张 4×4 的图像，其中有一个 2×2 的"纯红色块"（R=200, G=0, B=0），
 * 其余部分是白色（R=255, G=255, B=255）。
 *
 *   位置网格:
 *       (0,0)  (0,1)  (0,2)  (0,3)
 *       (1,0)  (1,1)  (1,2)  (1,3)
 *       (2,0)  (2,1)  (2,2)  (2,3)
 *       (3,0)  (3,1)  (3,2)  (3,3)
 *
 * ── 情况 A：Bayer Raw (RGGB) 中存储的内容 ──
 *
 *   真实颜色（如果去马赛克后）:               Bayer Raw 实际存储:
 *   ┌──────────────────────┐               ┌──────────────────────┐
 *   │红块 红块 白  白      │               │ R=200 G=0   R=255 G=255│
 *   │红块 红块 白  白      │               │ G=0   B=0   G=255 B=255│
 *   │白   白   白  白      │               │ R=255 G=255 R=255 G=255│
 *   │白   白   白  白      │               │ G=255 B=255 G=255 B=255│
 *   └──────────────────────┘               └──────────────────────┘
 *
 *   Bayer 的问题：
 *     (0,0) 存了 R=200，但 (0,0) 的 G 和 B 根本没测！
 *     (0,1) 存了 G=0，但 (0,1) 的 R 和 B 根本没测！
 *     你无法从单个字节判断这是什么颜色 —— 这真的是"马赛克"。
 *
 * ── 情况 B：YUV 4:2:0 中存储的内容 ──
 *
 *   经过 ISP 处理后的 RGB:                   YUV 4:2:0 实际存储:
 *   ┌──────────────────────┐               ┌──────────────────────────────┐
 *   │R200  R200  R255 R255 │               │ Y平面 (4×4, 全分辨率):       │
 *   │ G0    G0    G255 G255│               │  Y54  Y54  Y255 Y255        │
 *   │ B0    B0    B255 B255│               │  Y54  Y54  Y255 Y255        │
 *   │                      │               │  Y255 Y255 Y255 Y255        │
 *   │R200  R200  R255 R255 │               │  Y255 Y255 Y255 Y255        │
 *   │ G0    G0    G255 G255│               │                              │
 *   │ B0    B0    B255 B255│               │ U平面 (2×2, 1/4分辨率):      │
 *   │                      │               │  U_avg00  U_avg01           │
 *   │ ... (其余两行白色)    │               │  U_avg10  U_avg11           │
 *   └──────────────────────┘               │                              │
 *                                          │ V平面 (2×2, 1/4分辨率):      │
 *                                           │  V_avg00  V_avg01           │
 *   Y = 0.299R + 0.587G + 0.114B           │  V_avg10  V_avg11           │
 *   红色块: Y=0.299×200≈60                  └──────────────────────────────┘
 *   白色块: Y≈255
 *
 *   YUV 的关键区别：
 *     每个像素的 Y（亮度）都是真实的、完整分辨率的！不丢！
 *     只有 UV（色度）被做了 2×2 平均。丢失的是色度的空间细节，不是色度本身。
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 第三层：YUV→RGB 转回去会怎样？
 * ───────────────────────────────────────────────────────────────────────────
 *
 * 假设我们把上面的 YUV 4:2:0 再转回 RGB：
 *
 *   (0,0) 位置：Y=54, U=U_avg00, V=V_avg00
 *     → 反算出的 RGB ≈ (200, 0, 0)  ← 还是红色！
 *
 *   红色块的 4 个像素在 YUV→RGB 后会是什么颜色？
 *     都会是红色（R≈200, G≈0, B≈0），因为它们的 UV 来自同一个平均值，
 *     这个平均值正确地指向了"红色"方向。
 *
 *   会不会出现 Bayer 那样"一个像素只有 R 没有 G B"的情况？
 *     不会！每个像素转回 RGB 后都有完整的 R、G、B 三个值。
 *     YUV→RGB 的逆变换矩阵对所有像素都一样使用，每个像素必然输出完整的 RGB。
 *
 *   转回 RGB 后：
 *     - 每个像素仍然有完整的 R、G、B
 *     - 红色块区域仍然是红色（不会变成"只有红/只有绿"的马赛克）
 *     - 唯一的问题是：红色块内部的细微色彩变化会被抹平（因为 4 个像素共享 UV）
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 第四层：两种"分辨率损失"的直观对比
 * ───────────────────────────────────────────────────────────────────────────
 *
 *   对比维度          Bayer Raw                    YUV 4:2:0
 *   ─────────────────────────────────────────────────────────────────────
 *   每个像素有几个值    1 个（物理上只有一种颜色）   3 个（Y全分辨率 + UV共享）
 *
 *   丢失的"颜色"       R位置丢了G和B的值           每个2×2块内色度的细微差异
 *                     （从未测量过，需要猜测）       （测量过但被平均了）
 *
 *   转回 RGB 后       N/A（Bayer不是RGB）           每个像素都有完整RGB！
 *   每个像素完整吗？                                不会出现"某像素缺色"
 *
 *   视觉表现          网格状的马赛克图案             色块模糊、颜色渗漏
 *                     （颜色在像素间剧烈跳变）       （颜色过渡被柔化）
 *
 *   能否改进？        用更好的去马赛克算法            用 YUV 4:4:4 / 4:2:2
 *                     （高级插值、AI补全）           （保留更高的色度分辨率）
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 第五层：那为什么还要用 YUV 4:2:0？这不是在倒退吗？
 * ───────────────────────────────────────────────────────────────────────────
 *
 * 这是一个工程上的权衡（trade-off）：
 *
 *   人眼的生理特性：
 *     视网膜上的视杆细胞（感知亮度）约 1.2 亿个，密度极高
 *     视锥细胞（感知颜色）只有约 600 万个，密度低得多
 *     → 人眼对亮度细节极其敏感，对色度细节相对迟钝
 *
 *   所以 YUV 4:2:0 的设计非常精妙：
 *     - Y（亮度）：保存全部细节 ← 人眼最在意的，绝对不能丢
 *     - UV（色度）：降低分辨率 ← 人眼不太在意，可以适当压缩
 *
 *   结果：用 RGB 50% 的数据量（每像素 1.5 字节 vs 3 字节），
 *   就能达到几乎相同的视觉质量。这不是倒退，而是聪明的"感知无损"压缩。
 *
 *   Bayer → RGB（去马赛克）= 从 1/3 信息恢复 3/3 信息（插值猜测）
 *   RGB → YUV 4:2:0 = 从 3/3 信息压缩到 1.5/3 信息（感知无损丢弃）
 *
 *   两者的方向正好相反！Bayer 是"从少到多"（猜测），YUV 是"从多到少"（压缩）。
 *   YUV→RGB 的恢复质量远高于 Bayer→RGB，因为 YUV 并没有像 Bayer 那样
 *   在物理层面丢失了 2/3 的光谱信息。
 *
 * ───────────────────────────────────────────────────────────────────────────
 * 一句话回答你的问题
 * ───────────────────────────────────────────────────────────────────────────
 *
 *   RGB→YUV→RGB 不会产生 Bayer 式的马赛克。
 *
 *   因为 Bayer 的问题本质是"每个位置只知道一种颜色"，而 YUV 4:2:0 的问题是
 *   "每个位置知道三种颜色，只是色度被做了平滑处理"。转回 RGB 后每个像素仍然
 *   有完整的 R、G、B，绝不会出现"这个像素只有红、那个像素只有绿"的情况。
 *
 *   如果你反复做 RGB→YUV→RGB→YUV→RGB...（多代转换），色度会越来越模糊，
 *   但永远不会变成 Bayer 那样的马赛克。丢失的是细节，不是整个通道。
 *
 * 【为什么需要这个转换？】
 * 虽然 RGB 是显示的标准格式，但对于视频编码和传输来说效率很低：
 *   1. RGB 三通道都包含亮度信息，数据冗余大
 *   2. 人眼对亮度 (Y) 敏感，对色度 (UV) 不敏感
 *
 * 【YUV 色彩空间】
 *   Y  (Luma)    — 亮度分量（黑白图像信息）
 *   U  (Cb)      — 蓝色色度分量（蓝色 - 亮度）
 *   V  (Cr)      — 红色色度分量（红色 - 亮度）
 *
 * 【4:2:0 子采样】
 *   人眼对色度的分辨率不敏感，所以可以降低色度分量的采样率来节省空间。
 *
 *   4:2:0 的含义：对每 2×2 的 4 个亮度像素，只保存 1 个 U 和 1 个 V。
 *   这就是 "4个Y : 2个(水平) : 0个(垂直交替)" 的由来。
 *
 *   数据量：RGB 每像素 3 字节 → YUV 4:2:0 每像素仅 1.5 字节，节省 50%！
 *   这就是为什么几乎所有视频编码格式（H.264、H.265、VP9 等）都使用 YUV。
 *
 * 【转换公式（ITU-R BT.601）】
 *   Y  =  0.299×R + 0.587×G + 0.114×B
 *   U  = -0.169×R - 0.331×G + 0.500×B + 128
 *   V  =  0.500×R - 0.419×G - 0.081×B + 128
 *
 *   +128 是为了把 UV 的范围从 [-128,127] 偏移到 [0,255]（适合 uint8 存储）
 *
 * 【内存布局（平面格式 planar）】
 *   YUV 4:2:0 的三个分量分开存储（不是交织）：
 *
 *   [Y平面: width × height 字节]
 *   [U平面: (width/2) × (height/2) 字节]   ← 水平和垂直都缩小了一半
 *   [V平面: (width/2) × (height/2) 字节]
 *
 *   YUV420P 中的 "P" 就是指 Planar（平面）格式。
 *
 * ╔═══════════════════════════════════════════════════════════════════════════╗
 * ║  三种格式内存大小终极对比：RAW : YUV 4:2:0 : RGB24 = 1 : 1.5 : 3          ║
 * ╚═══════════════════════════════════════════════════════════════════════════╝
 *
 * 是的，你的比例完全正确！以 640×480 图像为例：
 *
 *   ┌──────────────┬──────────────────────┬────────────────┬──────────┐
 *   │ 格式          │ 每像素字节数           │ 文件大小        │ 相对比例  │
 *   ├──────────────┼──────────────────────┼────────────────┼──────────┤
 *   │ Bayer RAW    │ 1 字节/像素            │   307,200 字节  │   1×     │
 *   │              │ (每个感光单元1个颜色)    │   (0.29 MB)    │          │
 *   ├──────────────┼──────────────────────┼────────────────┼──────────┤
 *   │ YUV 4:2:0    │ 1.5 字节/像素          │   460,800 字节  │  1.5×    │
 *   │              │ (Y全分辨率+UV共享)      │   (0.44 MB)    │          │
 *   ├──────────────┼──────────────────────┼────────────────┼──────────┤
 *   │ RGB24        │ 3 字节/像素            │   921,600 字节  │   3×     │
 *   │              │ (每像素独立R,G,B)       │   (0.88 MB)    │          │
 *   └──────────────┴──────────────────────┴────────────────┴──────────┘
 *
 *   RAW  : YUV  : RGB
 *    1   : 1.5  :  3
 *    2   :  3   :  6    ← 通分后
 *
 * 这个比例关系的推导：
 *
 *   RAW  = W × H × 1          = W×H        ← 每个感光单元只采样一种颜色
 *   YUV  = W×H + W×H/4 + W×H/4 = 1.5×W×H  ← 亮度完整 + 色度压缩到 1/4
 *   RGB  = W × H × 3          = 3×W×H      ← 每个像素独立拥有全部三种颜色
 *
 * 重要补充：虽然 Bayer RAW 只有 RGB 的 1/3 大小，但它包含的"信息量"并不是
 * 简单等于 1/3。因为：
 *   - Bayer RAW 存储的是"传感器原始数据"（未经任何处理）
 *   - 去马赛克 + ISP 处理后，1 字节 Bayer → 3 字节 RGB
 *   - 这多出来的 2 字节是"算出来的"（通过插值），不是"测出来的"
 *   - 所以 RAW 体积小 = 它是压缩前的原料，不是压缩后的成品
 *
 * 这和视频编码的思路恰好相反：
 *   RAW → ISP → RGB：原料扩充（信息从少到多，靠算法填充）
 *   RGB → YUV → 编码：成品压缩（信息从多到少，靠人眼特性丢弃）
 *
 * ISP Pipeline 先"造"出 RGB（扩充 3 倍），再"压"成 YUV（缩小到 1.5 倍）。
 * 最终用于传输/存储的 YUV 只有 RAW 的 1.5 倍大，但质量远高于直接用 RAW。
 */
static void rgb_to_yuv420p(const uint8_t *rgb, uint8_t *yuv, const Config *cfg)
{
    const int width = cfg->width;
    const int height = cfg->height;
    // 色度平面的尺寸是亮度的一半（4:2:0 子采样）
    const int uv_width = width / 2;
    const int uv_height = height / 2;

    /*
     * 计算三个平面的起始指针：
     *
     * yuv 缓冲区在内存中的布局：
     * [0 ................ width*height) → Y 平面
     * [width*height ..... +uv_w*uv_h)  → U 平面
     * [+uv_w*uv_h ....... +uv_w*uv_h)  → V 平面
     */
    uint8_t *y_plane = yuv;                                          // Y  平面起始
    uint8_t *u_plane = yuv + width * height;                         // U  平面起始
    uint8_t *v_plane = u_plane + uv_width * uv_height;              // V  平面起始

    // 分配全分辨率的临时 UV 缓冲区（先降采样再压缩）
    uint8_t *u_full = (uint8_t *)malloc((size_t)width * (size_t)height);
    uint8_t *v_full = (uint8_t *)malloc((size_t)width * (size_t)height);

    int x;
    int y;

    if (!u_full || !v_full) {
        free(u_full);
        free(v_full);
        fprintf(stderr, "Out of memory converting RGB to YUV420P\n");
        exit(1);
    }

    /*
     * 步骤 1：逐像素 RGB → YUV 转换（全分辨率）
     *
     * 对每个像素做矩阵运算，得到全分辨率的 Y、U、V。
     */
    for (y = 0; y < height; ++y) {
        for (x = 0; x < width; ++x) {
            size_t rgb_idx = ((size_t)y * (size_t)width + (size_t)x) * 3u;
            size_t pos = (size_t)y * (size_t)width + (size_t)x;

            // 取出 RGB 值并归一化到 [0, 255]
            float r = (float)rgb[rgb_idx + 0];
            float g = (float)rgb[rgb_idx + 1];
            float b = (float)rgb[rgb_idx + 2];

            // ---- 应用 ITU-R BT.601 YUV 转换矩阵 ----
            // Y（亮度）：人眼对各颜色的加权平均
            float y_val = 0.299f * r + 0.587f * g + 0.114f * b;
            // U（蓝色色度）：蓝色减去亮度，再偏移 128
            float u_val = -0.168736f * r - 0.331264f * g + 0.5f * b + 128.0f;
            // V（红色色度）：红色减去亮度，再偏移 128
            float v_val = 0.5f * r - 0.418688f * g - 0.081312f * b + 128.0f;

            // 写入全分辨率缓冲区
            y_plane[pos] = clamp_u8(y_val);
            u_full[pos] = clamp_u8(u_val);
            v_full[pos] = clamp_u8(v_val);
        }
    }

    /*
     * 步骤 2：色度降采样（4:2:0 子采样）
     *
     * 对每 2×2 像素块，取 U 和 V 的平均值作为降采样结果。
     * 这就是 "2×2 的 4 个 Y 对应 1 个 U 和 1 个 V" 的来源。
     *
     * 遍历时 x 和 y 都以步长 2 前进（每次处理一个 2×2 的块）。
     */
    for (y = 0; y < height; y += 2) {
        for (x = 0; x < width; x += 2) {
            unsigned sum_u = 0;  // 2×2 块内 U 值的累加和
            unsigned sum_v = 0;  // 2×2 块内 V 值的累加和
            int dy;
            int dx;
            // 色度平面的坐标（除以 2）
            size_t uv_pos = (size_t)(y / 2) * (size_t)uv_width + (size_t)(x / 2);

            // 累加 2×2 块内的 4 个像素的 UV 值
            for (dy = 0; dy < 2; ++dy) {
                for (dx = 0; dx < 2; ++dx) {
                    int sx = x + dx;
                    int sy = y + dy;
                    size_t pos;

                    // 边界处理：如果图像尺寸不是偶数，超出边界的取边缘值
                    if (sx >= width)
                        sx = width - 1;
                    if (sy >= height)
                        sy = height - 1;

                    pos = (size_t)sy * (size_t)width + (size_t)sx;
                    sum_u += u_full[pos];
                    sum_v += v_full[pos];
                }
            }

            // 除以 4 取平均（(+2)/4 实现四舍五入的整数除法）
            u_plane[uv_pos] = (uint8_t)((sum_u + 2u) / 4u);
            v_plane[uv_pos] = (uint8_t)((sum_v + 2u) / 4u);
        }
    }

    // 释放临时全分辨率 UV 缓冲区
    free(u_full);
    free(v_full);
}

/* ====================================================================
 * ╔═══════════════════════════════════════════════════════════════════╗
 * ║            第 4 部分：Pipeline 的主调度函数                         ║
 * ║         （将各个阶段串联起来，完成完整的 ISP 处理流程）                ║
 * ╚═══════════════════════════════════════════════════════════════════╝
 * ====================================================================
 *
 * ╔═══════════════════════════════════════════════════════════════════════════╗
 * ║          输入文件解读：sensor_u8 中到底存放了什么？                          ║
 * ╚═══════════════════════════════════════════════════════════════════════════╝
 *
 * read_file_exact() 把 Bayer Raw 文件（如 synthetic_sensor_extreme_rggb8_640x480.raw）
 * 完整读入内存，得到一个 uint8_t 数组，命名为 sensor_u8。
 *
 * 这个数组的内容和布局：
 *
 *   sensor_u8 的类型:  uint8_t * （无符号 8 位整数数组）
 *   sensor_u8 的大小:  width × height 字节（640×480 = 307,200 字节）
 *   sensor_u8 的语义:  每个元素存储一个传感器像素的亮度值（0~255）
 *                      该像素属于 R/G/B 哪个通道由 Bayer Pattern (RGGB) 决定
 *
 * 内存中逐字节的含义（以 640×480 RGGB 为例）：
 *
 *   数组索引                 存放的数值              该像素的颜色
 *   ───────────────────────────────────────────────────────────────
 *   sensor_u8[0]           第0行第0列的亮度值       R 像素
 *   sensor_u8[1]           第0行第1列的亮度值       G 像素 (Gr)
 *   sensor_u8[2]           第0行第2列的亮度值       R 像素
 *   sensor_u8[3]           第0行第3列的亮度值       G 像素 (Gr)
 *   ...                    ...                     ...
 *   sensor_u8[639]         第0行第639列的亮度值     G 像素 (Gr)
 *   sensor_u8[640]         第1行第0列的亮度值       G 像素 (Gb)
 *   sensor_u8[641]         第1行第1列的亮度值       B 像素
 *   ...                    ...                     ...
 *   sensor_u8[307199]      第479行第639列的亮度值   B 像素 (奇数行奇数列)
 *
 * 访问公式：
 *   第 y 行、第 x 列的像素值 = sensor_u8[y * width + x]
 *
 * 重要：这个数组只存亮度值，没有颜色元数据！
 *   你必须预先知道：(1) 图像宽度 (2) 图像高度 (3) Bayer 排列方式 (RGGB)
 *   才能正确地把每个字节解释为"哪个颜色的像素"。
 *
 * 文件名中的 "rggb8" 含义：
 *   "rggb"  = Bayer 排列方式是 RGGB（本程序的默认模式）
 *   "8"     = 每个像素 8 位（0~255），即 uint8_t
 *   如果是 10/12/14 位的 Sensor，每个像素占 2 字节（uint16_t），
 *   数值范围会扩大到 0~1023 / 0~4095 / 0~16383。
 *
 * ───────────────────────────────────────────────────────────────────────────
 *
 * run_pipeline 是整个程序的核心：它负责：
 *   1. 读取输入的 Bayer Raw 数据（sensor_u8 数组，每元素1字节，只存亮度值）
 *   2. 创建输出目录
 *   3. 分配所有需要的缓冲区
 *   4. 按照 Pipeline 顺序依次调用每个处理阶段
 *   5. 保存每个阶段的中间结果到文件
 *   6. 可选：生成 PNG 预览图
 *   7. 释放所有分配的内存
 *
 * Pipeline 处理流程回顾：
 *
 *   输入: sensor_u8 (Bayer RGGB, uint8)
 *           ↑
 *           每个元素 = 0~255 的亮度值
 *           这个像素是什么颜色？→ 看坐标：(y偶数,x偶数)=R, (y奇数,x奇数)=B, 其他=G
 *     │
 *     ├─ Stage 1: subtract_black_level()  → black_plane (float)
 *     │   把每个字节值从 [black_level, 255] 映射到 [0.0, 1.0]
 *     │   sensor_u8[0]=200 → black_plane[0]=(200-64)/(255-64)≈0.712
 *     │   保存: 01_black_level_gray8.raw, 01_black_level.pgm
 *     │
 *     ├─ Stage 2: apply_lsc_and_wb()      → lsc_wb_plane (float)
 *     │   对每个像素：根据坐标判断颜色 → 选择对应的 WB 增益 → 乘 LSC 径向增益
 *     │   保存: 02_lsc_wb_gray8.raw, 02_lsc_wb.pgm
 *     │
 *     ├─ Stage 3: demosaic_and_finish()   → linear_rgb + display_rgb (uint8)
 *     │   从 Bayer 单色数据 → 每个像素补全 R、G、B 三个值（去马赛克插值）
 *     │   → CCM 颜色校正 → 饱和度调整 → Gamma 编码
 *     │   保存: 03_demosaic_linear_rgb24.raw (线性RGB)
 *     │   保存: 04_display_rgb24.raw (完整处理RGB)
 *     │
 *     └─ Stage 4: rgb_to_yuv420p()        → display_yuv (uint8)
 *         从 RGB 三通道 → YUV 4:2:0（亮度 + 降采样的色度）
 *         保存: 05_display_yuv420p.raw
 *
 * 这种设计就是 "Pipeline 模式" 的精髓：
 *   每个阶段输入 + 处理 + 输出，互不干扰，链条清晰。
 */
static int run_pipeline(const Config *cfg)
{
    // ---- 计算各阶段需要的缓冲区大小 ----
    const int pixel_count = cfg->width * cfg->height;                                    // 像素总数
    const size_t bayer_size = (size_t)pixel_count;                                       // Bayer: 每像素1字节
    const size_t rgb_size = (size_t)pixel_count * 3u;                                   // RGB: 每像素3字节
    const size_t yuv_size = (size_t)pixel_count                                          // YUV420P 总大小
                            + 2u * (size_t)(cfg->width / 2) * (size_t)(cfg->height / 2); // = Y + U + V

    // ---- 声明缓冲区指针 ----
    uint8_t *sensor_u8;       // 输入：Bayer Raw 数据（uint8_t）
    float *black_plane;       // 阶段1输出：黑电平校正后的 Bayer 数据（float）
    float *lsc_wb_plane;      // 阶段2输出：LSC+WB 后的 Bayer 数据（float）
    uint8_t *black_u8;        // 阶段1的 uint8 版本（用于保存文件/预览）
    uint8_t *lsc_wb_u8;       // 阶段2的 uint8 版本（用于保存文件/预览）
    uint8_t *linear_rgb;      // 阶段3输出1：去马赛克后的线性 RGB
    uint8_t *display_rgb;     // 阶段3输出2：完整处理后的显示 RGB
    uint8_t *display_yuv;     // 阶段4输出：YUV 4:2:0

    // ---- 声明输出文件路径缓冲区 ----
    char path[512];
    char raw00_path[512], raw01_path[512], raw02_path[512];
    char raw03_path[512], raw04_path[512], raw05_path[512];
    char preview00_path[512], preview01_path[512], preview02_path[512];
    char preview03_path[512], preview04_path[512], preview05_path[512];

    // ---- 步骤 0: 读取输入数据 ----
    sensor_u8 = read_file_exact(cfg->input_bayer_path, bayer_size);
    if (!sensor_u8)
        return -1;

    // ---- 步骤 0.5: 确保输出目录存在 ----
    if (ensure_dir(cfg->output_dir) != 0) {
        free(sensor_u8);
        return -1;
    }

    // ---- 分配所有缓冲区 ----
    // 在 Pipeline 模式中，我们预先分配所有需要的内存，
    // 避免在运行中频繁 malloc/free，提高效率。
    black_plane = (float *)malloc(sizeof(float) * (size_t)pixel_count);
    lsc_wb_plane = (float *)malloc(sizeof(float) * (size_t)pixel_count);
    black_u8 = (uint8_t *)malloc(bayer_size);
    lsc_wb_u8 = (uint8_t *)malloc(bayer_size);
    linear_rgb = (uint8_t *)malloc(rgb_size);
    display_rgb = (uint8_t *)malloc(rgb_size);
    display_yuv = (uint8_t *)malloc(yuv_size);

    // 检查所有内存分配是否成功
    if (!black_plane || !lsc_wb_plane || !black_u8 || !lsc_wb_u8 ||
        !linear_rgb || !display_rgb || !display_yuv) {
        fprintf(stderr, "Out of memory in ISP pipeline\n");
        // 即使分配失败，free(NULL) 也是安全的，所以可以统一释放
        free(sensor_u8);
        free(black_plane);
        free(lsc_wb_plane);
        free(black_u8);
        free(lsc_wb_u8);
        free(linear_rgb);
        free(display_rgb);
        free(display_yuv);
        return -1;
    }

    /*
     * ================================================================
     * ╔══════════════════════════════════════════════════════════════╗
     * ║              ISP Pipeline 主处理流程（核心！）                ║
     * ╚══════════════════════════════════════════════════════════════╝
     *
     * 观察下面的调用顺序：每个阶段的输出直接成为下一个阶段的输入。
     * 这就是 "Pipeline（流水线）" 模式的最直观体现。
     *
     * 数据像流水一样经过：
     *   sensor_u8 → black_plane → lsc_wb_plane → linear_rgb/display_rgb → display_yuv
     * ================================================================
     */

    // ---- Stage 1: 黑电平校正 ----
    // 输入: sensor_u8 (Bayer, uint8_t)
    // 输出: black_plane (Bayer, float)
    subtract_black_level(sensor_u8, black_plane, pixel_count, cfg->black_level);

    // ---- Stage 2: 镜头阴影校正 (LSC) + 白平衡 (WB) ----
    // 输入: black_plane (Bayer, float)
    // 输出: lsc_wb_plane (Bayer, float)
    apply_lsc_and_wb(black_plane, lsc_wb_plane, cfg);

    // 将阶段1和阶段2的 float 结果转为 uint8_t（用于保存文件）
    plane_to_u8(black_plane, black_u8, pixel_count);
    plane_to_u8(lsc_wb_plane, lsc_wb_u8, pixel_count);

    // ---- Stage 3: 去马赛克 + CCM + 饱和度 + Gamma ----
    // 输入: lsc_wb_plane (Bayer, float)
    // 输出: linear_rgb (RGB, uint8_t) — 中间结果
    //       display_rgb (RGB, uint8_t) — 最终结果
    demosaic_and_finish(lsc_wb_plane, linear_rgb, display_rgb, cfg);

    // ---- Stage 4: 色彩空间转换 (RGB → YUV 4:2:0) ----
    // 输入: display_rgb (RGB, uint8_t)
    // 输出: display_yuv (YUV420P, uint8_t)
    rgb_to_yuv420p(display_rgb, display_yuv, cfg);

    /*
     * ================================================================
     * 保存各阶段的输出文件
     *
     * 每个阶段生成两种文件：
     *   1. .raw 文件 — 原始二进制像素数据（供后续程序使用或 ffplay 查看）
     *   2. .pgm/.ppm 文件 — 带文件头的可读格式（可直接用图像查看器打开）
     *   3. 可选 .png 预览 — 用 ffmpeg 生成（更方便查看）
     *
     * 文件名中的数字前缀（00, 01, 02...）表示 Pipeline 的处理顺序。
     * ================================================================
     */

    // ---- 阶段0 输出：原始 Sensor Bayer 数据 ----
    snprintf(raw00_path, sizeof(raw00_path), "%s/00_sensor_mosaic_rggb8.raw", cfg->output_dir);
    write_file(raw00_path, sensor_u8, bayer_size);
    snprintf(path, sizeof(path), "%s/00_sensor_mosaic.pgm", cfg->output_dir);
    write_pgm(path, cfg->width, cfg->height, sensor_u8, bayer_size);
    snprintf(preview00_path, sizeof(preview00_path), "%s/00_sensor_preview.png", cfg->output_dir);

    // ---- 阶段1 输出：黑电平校正后 ----
    snprintf(raw01_path, sizeof(raw01_path), "%s/01_black_level_gray8.raw", cfg->output_dir);
    write_file(raw01_path, black_u8, bayer_size);
    snprintf(path, sizeof(path), "%s/01_black_level.pgm", cfg->output_dir);
    write_pgm(path, cfg->width, cfg->height, black_u8, bayer_size);
    snprintf(preview01_path, sizeof(preview01_path), "%s/01_black_level_preview.png", cfg->output_dir);

    // ---- 阶段2 输出：LSC + 白平衡后 ----
    snprintf(raw02_path, sizeof(raw02_path), "%s/02_lsc_wb_gray8.raw", cfg->output_dir);
    write_file(raw02_path, lsc_wb_u8, bayer_size);
    snprintf(path, sizeof(path), "%s/02_lsc_wb.pgm", cfg->output_dir);
    write_pgm(path, cfg->width, cfg->height, lsc_wb_u8, bayer_size);
    snprintf(preview02_path, sizeof(preview02_path), "%s/02_lsc_wb_preview.png", cfg->output_dir);

    // ---- 阶段3 输出1：去马赛克后的线性 RGB（无 Gamma） ----
    //
    // 【此时数据已从 Bayer 转换为 RGB24】
    // 单个文件大小从 bayer_size(307,200 字节) 变为 rgb_size(921,600 字节)，增大 3 倍。
    // 每个像素现在有 3 个字节 [R][G][B]，不再需要"查坐标猜颜色"。
    //
    // linear_rgb 存储的是"物理线性光强度"——暗部很暗（因为人眼和显示器都不是线性的），
    // 看起来会比正常图片偏黑，但这才是物理上正确的亮度关系。
    snprintf(raw03_path, sizeof(raw03_path), "%s/03_demosaic_linear_rgb24.raw", cfg->output_dir);
    write_file(raw03_path, linear_rgb, rgb_size);
    snprintf(path, sizeof(path), "%s/03_demosaic_linear.ppm", cfg->output_dir);
    write_ppm(path, cfg->width, cfg->height, linear_rgb, rgb_size);
    snprintf(preview03_path, sizeof(preview03_path), "%s/03_demosaic_linear_preview.png", cfg->output_dir);

    // ---- 阶段3 输出2：完整处理后的 RGB（含 CCM + 饱和度 + Gamma） ----
    //
    // display_rgb 经过了 Gamma 编码（^0.45），暗部被大幅提亮：
    //   例如物理光强度 0.2 → linear_rgb 存 51，display_rgb 存 ~120。
    // 这个文件可以直接在屏幕上观看，看起来就是"正常"的照片。
    snprintf(raw04_path, sizeof(raw04_path), "%s/04_display_rgb24.raw", cfg->output_dir);
    write_file(raw04_path, display_rgb, rgb_size);
    snprintf(path, sizeof(path), "%s/04_display.ppm", cfg->output_dir);
    write_ppm(path, cfg->width, cfg->height, display_rgb, rgb_size);
    snprintf(preview04_path, sizeof(preview04_path), "%s/04_display_preview.png", cfg->output_dir);

    // ---- 阶段4 输出：YUV 4:2:0 ----
    snprintf(raw05_path, sizeof(raw05_path), "%s/05_display_yuv420p.raw", cfg->output_dir);
    write_file(raw05_path, display_yuv, yuv_size);
    snprintf(preview05_path, sizeof(preview05_path), "%s/05_display_yuv420p_preview.png", cfg->output_dir);

    // ---- 可选：用 ffmpeg 生成 PNG 预览图 ----
    if (cfg->generate_previews) {
        generate_preview_png(raw00_path, preview00_path, "gray", cfg->width, cfg->height);
        generate_preview_png(raw01_path, preview01_path, "gray", cfg->width, cfg->height);
        generate_preview_png(raw02_path, preview02_path, "gray", cfg->width, cfg->height);
        generate_preview_png(raw03_path, preview03_path, "rgb24", cfg->width, cfg->height);
        generate_preview_png(raw04_path, preview04_path, "rgb24", cfg->width, cfg->height);
        generate_preview_png(raw05_path, preview05_path, "yuv420p", cfg->width, cfg->height);
    }

    // ---- 打印处理结果信息 ----
    printf("C ISP demo finished.\n");
    printf("Input Bayer : %s\n", cfg->input_bayer_path);
    printf("Output dir  : %s\n", cfg->output_dir);
    printf("View commands:\n");
    // 用 ffplay 可以直接查看 Raw 文件（需要指定像素格式和尺寸）
    printf("  ffplay -f rawvideo -pixel_format gray -video_size %dx%d %s/00_sensor_mosaic_rggb8.raw\n",
           cfg->width, cfg->height, cfg->output_dir);
    printf("  ffplay -f rawvideo -pixel_format gray -video_size %dx%d %s/02_lsc_wb_gray8.raw\n",
           cfg->width, cfg->height, cfg->output_dir);
    printf("  ffplay -f rawvideo -pixel_format rgb24 -video_size %dx%d %s/04_display_rgb24.raw\n",
           cfg->width, cfg->height, cfg->output_dir);
    printf("  ffplay -f rawvideo -pixel_format yuv420p -video_size %dx%d %s/05_display_yuv420p.raw\n",
           cfg->width, cfg->height, cfg->output_dir);

    if (cfg->generate_previews) {
        printf("Preview PNGs:\n");
        printf("  %s\n", preview00_path);
        printf("  %s\n", preview01_path);
        printf("  %s\n", preview02_path);
        printf("  %s\n", preview03_path);
        printf("  %s\n", preview04_path);
        printf("  %s\n", preview05_path);
    }

    // ---- 释放所有分配的内存 ----
    // Pipeline 模式中，输入数据在当前阶段输出后可能就不需要了。
    // 但在我们这个简单的实现中，一次性处理完再统一释放。
    free(sensor_u8);
    free(black_plane);
    free(lsc_wb_plane);
    free(black_u8);
    free(lsc_wb_u8);
    free(linear_rgb);
    free(display_rgb);
    free(display_yuv);

    return 0;
}

